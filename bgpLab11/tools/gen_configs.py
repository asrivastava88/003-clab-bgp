#!/usr/bin/env python3
"""
bgp-lab11 config renderer (stdlib only). The capstone.

A two-VRF EVPN-VXLAN fabric with a dual border and a WAN. Nothing in the
topology is novel; everything from labs 01 to 10 is here at once. What is
different is the fault model: these faults do not announce themselves.

There is no 'base' mode. The lab ships working and your job is to find out
in how many ways it has been quietly broken.
"""
from pathlib import Path

SPINE_ASN, WAN_ASN = 65100, 65200
VMAC = "00:1c:73:00:00:99"
VRFS = {"RED": 50001, "BLUE": 50002}

VLANS = {
    10: {"name": "RED_WEB", "vrf": "RED",  "gw": "10.10.10.1/24", "vni": 10010},
    20: {"name": "RED_DB",  "vrf": "RED",  "gw": "10.10.20.1/24", "vni": 10020},
    30: {"name": "BLU_APP", "vrf": "BLUE", "gw": "10.30.30.1/24", "vni": 10030},
}

SPINES = {"spine1": {"sid": 1, "n": 1}, "spine2": {"sid": 2, "n": 2}}

LEAVES = {
    "leaf1":  {"asn": 65101, "n": 11, "idx": 1, "vlans": [10],     "access": {3: (10, "h1")}},
    "leaf2":  {"asn": 65102, "n": 12, "idx": 2, "vlans": [10],     "access": {3: (10, "h2")}},
    "leaf3":  {"asn": 65103, "n": 13, "idx": 3, "vlans": [20, 30], "access": {4: (30, "h3")}},
    # dual border. bleaf2 prepends inbound so bleaf1 is primary for both VRFs
    # and bleaf2 is a backup nobody exercises, which is the point of fault 3.
    "bleaf1": {"asn": 65104, "n": 14, "idx": 4, "vlans": [], "access": {}, "prepend": 0,
               "wan": {"RED": (101, "172.16.11.1/30", "172.16.11.2"),
                       "BLUE": (102, "172.16.12.1/30", "172.16.12.2")}},
    "bleaf2": {"asn": 65105, "n": 15, "idx": 5, "vlans": [], "access": {}, "prepend": 2,
               "wan": {"RED": (101, "172.16.21.1/30", "172.16.21.2"),
                       "BLUE": (102, "172.16.22.1/30", "172.16.22.2")}},
}

HOSTS = {
    "h1": {"ip": "10.10.10.101/24", "gw": "10.10.10.1", "to": "leaf1 vlan 10 RED"},
    "h2": {"ip": "10.10.10.102/24", "gw": "10.10.10.1", "to": "leaf2 vlan 10 RED, same subnet as h1"},
    "h3": {"ip": "10.30.30.101/24", "gw": "10.30.30.1", "to": "leaf3 vlan 30 BLUE"},
}

WAN_PORT = 3           # physical port facing wan on each border
TENANT = {"RED": "10.10.0.0/16", "BLUE": "10.30.0.0/16"}
INET = "203.0.113.0/24"


def lo0(n): return f"10.0.0.{n}"
def lo1(n): return f"10.0.1.{n}"
def p2p(sid, idx):
    b = (idx - 1) * 2
    return f"10.1.{sid}.{b}", f"10.1.{sid}.{b+1}"


def header(h):
    return f"""! {h} | bgp-lab11 | generated by tools/gen_configs.py
hostname {h}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode mstp
!
"""


LOOPS = """ip prefix-list PL-LOOPBACKS seq 10 permit 10.0.0.0/24 eq 32
ip prefix-list PL-LOOPBACKS seq 20 permit 10.0.1.0/24 eq 32
!
route-map RM-CONN-2-BGP permit 10
   match ip address prefix-list PL-LOOPBACKS
!
"""


def spine(name, d):
    c = header(name)
    for lf, ld in LEAVES.items():
        s, _ = p2p(d["sid"], ld["idx"])
        c += (f"interface Ethernet{ld['idx']}\n   description P2P_{lf}\n"
              f"   no switchport\n   mtu 9214\n   ip address {s}/31\n!\n")
    c += f"interface Loopback0\n   ip address {lo0(d['n'])}/32\n!\nip routing\n!\n" + LOOPS
    c += f"""router bgp {SPINE_ASN}
   router-id {lo0(d['n'])}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN next-hop-unchanged
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community extended
   neighbor EVPN maximum-routes 0
"""
    for lf, ld in LEAVES.items():
        _, l = p2p(d["sid"], ld["idx"])
        c += (f"   neighbor {l} peer group UNDERLAY\n   neighbor {l} remote-as {ld['asn']}\n"
              f"   neighbor {l} description {lf}\n")
    for lf, ld in LEAVES.items():
        c += (f"   neighbor {lo0(ld['n'])} peer group EVPN\n"
              f"   neighbor {lo0(ld['n'])} remote-as {ld['asn']}\n"
              f"   neighbor {lo0(ld['n'])} description {lf}-evpn\n")
    c += ("   redistribute connected route-map RM-CONN-2-BGP\n   !\n"
          "   address-family evpn\n      neighbor EVPN activate\n   !\n"
          "   address-family ipv4\n      neighbor UNDERLAY activate\n!\nend\n")
    return c


def leaf(name, d):
    n, asn = d["n"], d["asn"]
    vl = sorted(d["vlans"])
    border = "wan" in d
    vrfs = list(VRFS) if border else sorted({VLANS[v]["vrf"] for v in vl})
    c = header(name)
    for v in vl:
        c += f"vlan {v}\n   name {VLANS[v]['name']}\n!\n"
    for vrf in vrfs:
        c += f"vrf instance {vrf}\n!\n"
    for sn, sd in SPINES.items():
        _, l = p2p(sd["sid"], d["idx"])
        c += (f"interface Ethernet{sd['sid']}\n   description P2P_{sn}\n"
              f"   no switchport\n   mtu 9214\n   ip address {l}/31\n!\n")
    for port, (v, h) in sorted(d["access"].items()):
        c += (f"interface Ethernet{port}\n   description HOST_{h}\n"
              f"   switchport access vlan {v}\n   spanning-tree portfast\n"
              f"   spanning-tree bpduguard enable\n!\n")
    if border:
        c += f"interface Ethernet{WAN_PORT}\n   description WAN_handoff\n   no switchport\n   mtu 9214\n!\n"
        for vrf, (tag, ip, _) in d["wan"].items():
            c += (f"interface Ethernet{WAN_PORT}.{tag}\n   description WAN_vrf_{vrf}\n"
                  f"   encapsulation dot1q vlan {tag}\n   vrf {vrf}\n   ip address {ip}\n!\n")
    c += (f"interface Loopback0\n   description ROUTER_ID_EVPN\n   ip address {lo0(n)}/32\n!\n"
          f"interface Loopback1\n   description VTEP\n   ip address {lo1(n)}/32\n!\n")
    for v in vl:
        c += (f"interface Vlan{v}\n   description {VLANS[v]['name']}\n   vrf {VLANS[v]['vrf']}\n"
              f"   ip address virtual {VLANS[v]['gw']}\n!\n")
    c += "interface Vxlan1\n   vxlan source-interface Loopback1\n   vxlan udp-port 4789\n"
    for v in vl:
        c += f"   vxlan vlan {v} vni {VLANS[v]['vni']}\n"
    for vrf in vrfs:
        c += f"   vxlan vrf {vrf} vni {VRFS[vrf]}\n"
    c += f"!\nip virtual-router mac-address {VMAC}\n!\nip routing\n"
    for vrf in vrfs:
        c += f"ip routing vrf {vrf}\n"
    c += "!\n" + LOOPS
    if border:
        for vrf, net in TENANT.items():
            c += f"ip prefix-list PL-{vrf}-TENANT seq 10 permit {net} le 24\n!\n"
        c += f"ip prefix-list PL-FROM-WAN seq 10 permit 0.0.0.0/0\nip prefix-list PL-FROM-WAN seq 20 permit {INET}\n!\n"
        for vrf in VRFS:
            pre = ""
            if d["prepend"]:
                pre = f"   set as-path prepend{(' ' + str(asn)) * d['prepend']}\n"
            c += (f"route-map RM-{vrf}-IN permit 10\n"
                  f"   match ip address prefix-list PL-FROM-WAN\n{pre}!\n"
                  f"route-map RM-{vrf}-OUT permit 10\n"
                  f"   match ip address prefix-list PL-{vrf}-TENANT\n!\n")
    c += f"""router bgp {asn}
   router-id {lo0(n)}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY remote-as {SPINE_ASN}
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN remote-as {SPINE_ASN}
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community extended
   neighbor EVPN maximum-routes 0
"""
    for sn, sd in SPINES.items():
        s, _ = p2p(sd["sid"], d["idx"])
        c += f"   neighbor {s} peer group UNDERLAY\n   neighbor {s} description {sn}\n"
    for sn, sd in SPINES.items():
        c += f"   neighbor {lo0(sd['n'])} peer group EVPN\n   neighbor {lo0(sd['n'])} description {sn}-evpn\n"
    c += "   redistribute connected route-map RM-CONN-2-BGP\n   !\n"
    for v in vl:
        vni = VLANS[v]["vni"]
        c += (f"   vlan {v}\n      rd {lo0(n)}:{vni}\n      route-target both {vni}:{vni}\n"
              f"      redistribute learned\n   !\n")
    c += ("   address-family evpn\n      neighbor EVPN activate\n   !\n"
          "   address-family ipv4\n      neighbor UNDERLAY activate\n   !\n")
    for vrf in vrfs:
        l3 = VRFS[vrf]
        c += (f"   vrf {vrf}\n      rd {lo0(n)}:{l3}\n"
              f"      route-target import evpn {l3}:{l3}\n"
              f"      route-target export evpn {l3}:{l3}\n"
              f"      router-id {lo0(n)}\n      maximum-paths 4 ecmp 4\n")
        if border:
            _, _, peer = d["wan"][vrf]
            c += (f"      neighbor {peer} remote-as {WAN_ASN}\n"
                  f"      neighbor {peer} description wan-{vrf}\n"
                  f"      neighbor {peer} route-map RM-{vrf}-IN in\n"
                  f"      neighbor {peer} route-map RM-{vrf}-OUT out\n"
                  f"      neighbor {peer} maximum-routes 1000\n")
        c += "      redistribute connected\n"
        if border:
            _, _, peer = d["wan"][vrf]
            c += f"      !\n      address-family ipv4\n         neighbor {peer} activate\n"
        c += "   !\n"
    return c + "!\nend\n"


def wan():
    c = header("wan")
    peers = []
    for i, (b, bd) in enumerate([(k, v) for k, v in LEAVES.items() if "wan" in v], start=1):
        c += f"interface Ethernet{i}\n   description CUST_{b}\n   no switchport\n   mtu 9214\n!\n"
        for vrf, (tag, _, myip) in bd["wan"].items():
            far = bd["wan"][vrf][1].split("/")[0]
            c += (f"interface Ethernet{i}.{tag}\n   description CUST_{b}_{vrf}\n"
                  f"   encapsulation dot1q vlan {tag}\n   ip address {myip}/30\n!\n")
            peers.append((far, f"{b}-{vrf}", bd["asn"]))
    c += (f"interface Loopback0\n   ip address 10.255.0.1/32\n!\n"
          f"interface Loopback1\n   description internet target\n   ip address 203.0.113.10/24\n!\n"
          f"ip routing\n!\nip route {INET} Null0\n!\n")
    c += f"router bgp {WAN_ASN}\n   router-id 10.255.0.1\n   no bgp default ipv4-unicast\n   maximum-paths 4 ecmp 4\n"
    for ip, desc, asn in peers:
        c += (f"   neighbor {ip} remote-as {asn}\n   neighbor {ip} description {desc}\n"
              f"   neighbor {ip} default-originate\n   neighbor {ip} maximum-routes 1000\n")
    c += f"   network {INET}\n   !\n   address-family ipv4\n"
    for ip, _, _ in peers:
        c += f"      neighbor {ip} activate\n"
    return c + "!\nend\n"


def host(name, d):
    return (header(name) + f"! {name} -> {d['to']}\n!\nspanning-tree mode none\n!\n"
            f"interface Ethernet1\n   description UPLINK\n   no switchport\n   mtu 9214\n"
            f"   ip address {d['ip']}\n!\nip routing\n!\nip route 0.0.0.0/0 {d['gw']}\n!\nend\n")


def main():
    out = Path(__file__).resolve().parent.parent / "configs" / "solution"
    out.mkdir(parents=True, exist_ok=True)
    for s, d in SPINES.items():
        (out / f"{s}.cfg").write_text(spine(s, d))
    for l, d in LEAVES.items():
        (out / f"{l}.cfg").write_text(leaf(l, d))
    (out / "wan.cfg").write_text(wan())
    for h, d in HOSTS.items():
        (out / f"{h}.cfg").write_text(host(h, d))
    print("rendered configs/solution")


if __name__ == "__main__":
    main()
