#!/usr/bin/env python3
"""
bgp-lab09 config renderer (stdlib only).

Convergence and resiliency. The fabric is deliberately ordinary; the subject
is how fast it recovers and what makes it fast.

Three failure classes, three knobs:

  hard link failure   carrier drops. Fast by default IF you have ECMP.
  grey failure        carrier stays up, traffic disappears. Only BFD catches
                      this; BGP will sit on its hold timer.
  planned maintenance not a failure at all. Drain first, then touch it.

  knobs: BFD (detection), timers (fallback detection), ECMP (absorption)

Modes:
  base      the fabric works and converges terribly. Default 60/180 timers,
            no BFD anywhere, maximum-paths 1. Every failure is an outage.
  solution  tuned: BFD on every session, 3/9 timers as the fallback,
            ECMP everywhere including inside the VRF.
"""
from pathlib import Path

# ============================ DATA ============================
SPINE_ASN = 65100
WAN_ASN = 65200
VMAC = "00:1c:73:00:00:99"
VRF, L3VNI = "RED", 50001

# The tuned values. base mode gets none of them.
BFD_IFACE = "bfd interval 300 min-rx 300 multiplier 3"
BGP_TIMERS = "timers 3 9"
ECMP = 4

VLANS = {
    10: {"name": "WEB", "vrf": VRF, "gw": "10.10.10.1/24", "vni": 10010},
    20: {"name": "APP", "vrf": VRF, "gw": "10.10.20.1/24", "vni": 10020},
}

SPINES = {"spine1": {"sid": 1, "n": 1}, "spine2": {"sid": 2, "n": 2}}

LEAVES = {
    "leaf1":  {"asn": 65101, "n": 11, "idx": 1, "vlans": [10],
               "access": {3: (10, "h1")}},
    "leaf2":  {"asn": 65102, "n": 12, "idx": 2, "vlans": [10, 20],
               "access": {3: (10, "h2"), 4: (20, "h3")}},
    "bleaf1": {"asn": 65104, "n": 14, "idx": 3, "vlans": [],
               "access": {}, "wan": (3, "172.16.1.1/30", "172.16.1.2")},
    "bleaf2": {"asn": 65105, "n": 15, "idx": 4, "vlans": [],
               "access": {}, "wan": (3, "172.16.2.1/30", "172.16.2.2")},
}

WAN = {"asn": WAN_ASN, "lo0": "10.255.0.1", "target": "203.0.113.10",
       "net": "203.0.113.0/24",
       # two border handoffs, so the tenant VRF has two default routes and
       # per-VRF ECMP is something you can measure rather than read
       "links": {1: ("bleaf1", 65104, "172.16.1.2/30", "172.16.1.1"),
                 2: ("bleaf2", 65105, "172.16.2.2/30", "172.16.2.1")}}

HOSTS = {
    "h1": {"ip": "10.10.10.101/24", "gw": "10.10.10.1", "to": "leaf1 vlan 10"},
    "h2": {"ip": "10.10.10.102/24", "gw": "10.10.10.1", "to": "leaf2 vlan 10"},
    "h3": {"ip": "10.10.20.103/24", "gw": "10.10.20.1", "to": "leaf2 vlan 20"},
}
# ==============================================================


def lo0(n):
    return f"10.0.0.{n}"


def lo1(n):
    return f"10.0.1.{n}"


def p2p(sid, idx):
    b = (idx - 1) * 2
    return f"10.1.{sid}.{b}", f"10.1.{sid}.{b + 1}"


def header(host, mode):
    return f"""! {host} | bgp-lab09 | {mode} | generated by tools/gen_configs.py
hostname {host}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode mstp
!
"""


LOOP_POLICY = """ip prefix-list PL-LOOPBACKS seq 10 permit 10.0.0.0/24 eq 32
ip prefix-list PL-LOOPBACKS seq 20 permit 10.0.1.0/24 eq 32
!
route-map RM-CONN-2-BGP permit 10
   match ip address prefix-list PL-LOOPBACKS
!
"""


def fabric_iface(port, desc, ip, mode):
    c = (f"interface Ethernet{port}\n   description {desc}\n"
         f"   no switchport\n   mtu 9214\n   ip address {ip}\n")
    if mode == "solution":
        c += f"   {BFD_IFACE}\n"
    return c + "!\n"


def tuning(mode, groups):
    """BFD and timers per peer group. In base mode none of this exists, which
    is the point: the fabric works and takes three minutes to notice anything."""
    if mode != "solution":
        return ""
    c = ""
    for g in groups:
        c += f"   neighbor {g} bfd\n   neighbor {g} {BGP_TIMERS}\n"
    return c


def paths(mode):
    return f"   maximum-paths {ECMP} ecmp {ECMP}\n" if mode == "solution" else "   maximum-paths 1\n"


def spine(name, d, mode):
    c = header(name, mode)
    for leaf, ld in LEAVES.items():
        s_ip, _ = p2p(d["sid"], ld["idx"])
        c += fabric_iface(ld["idx"], f"P2P_{leaf}", f"{s_ip}/31", mode)
    c += f"interface Loopback0\n   ip address {lo0(d['n'])}/32\n!\nip routing\n!\n" + LOOP_POLICY
    c += f"router bgp {SPINE_ASN}\n   router-id {lo0(d['n'])}\n   no bgp default ipv4-unicast\n"
    c += paths(mode)
    c += """   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN next-hop-unchanged
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community extended
   neighbor EVPN maximum-routes 0
"""
    c += tuning(mode, ["UNDERLAY"])
    for leaf, ld in LEAVES.items():
        _, l_ip = p2p(d["sid"], ld["idx"])
        c += (f"   neighbor {l_ip} peer group UNDERLAY\n"
              f"   neighbor {l_ip} remote-as {ld['asn']}\n"
              f"   neighbor {l_ip} description {leaf}\n")
    for leaf, ld in LEAVES.items():
        c += (f"   neighbor {lo0(ld['n'])} peer group EVPN\n"
              f"   neighbor {lo0(ld['n'])} remote-as {ld['asn']}\n"
              f"   neighbor {lo0(ld['n'])} description {leaf}-evpn\n")
    c += """   redistribute connected route-map RM-CONN-2-BGP
   !
   address-family evpn
      neighbor EVPN activate
   !
   address-family ipv4
      neighbor UNDERLAY activate
!
end
"""
    return c


def leaf(name, d, mode):
    n, asn = d["n"], d["asn"]
    vlans = sorted(d["vlans"])
    is_border = "wan" in d
    c = header(name, mode)
    for v in vlans:
        c += f"vlan {v}\n   name {VLANS[v]['name']}\n!\n"
    c += f"vrf instance {VRF}\n!\n"

    for sname, sd in SPINES.items():
        _, l_ip = p2p(sd["sid"], d["idx"])
        c += fabric_iface(sd["sid"], f"P2P_{sname}", f"{l_ip}/31", mode)

    for port, (v, h) in sorted(d["access"].items()):
        c += (f"interface Ethernet{port}\n   description HOST_{h}\n"
              f"   switchport access vlan {v}\n   spanning-tree portfast\n"
              f"   spanning-tree bpduguard enable\n!\n")

    if is_border:
        port, ip, _ = d["wan"]
        c += (f"interface Ethernet{port}\n   description WAN_vrf_{VRF}\n"
              f"   no switchport\n   vrf {VRF}\n   ip address {ip}\n")
        if mode == "solution":
            c += f"   {BFD_IFACE}\n"
        c += "!\n"

    c += (f"interface Loopback0\n   description ROUTER_ID_EVPN\n   ip address {lo0(n)}/32\n!\n"
          f"interface Loopback1\n   description VTEP\n   ip address {lo1(n)}/32\n!\n")
    for v in vlans:
        c += (f"interface Vlan{v}\n   description {VLANS[v]['name']}\n   vrf {VRF}\n"
              f"   ip address virtual {VLANS[v]['gw']}\n!\n")
    c += "interface Vxlan1\n   vxlan source-interface Loopback1\n   vxlan udp-port 4789\n"
    for v in vlans:
        c += f"   vxlan vlan {v} vni {VLANS[v]['vni']}\n"
    c += f"   vxlan vrf {VRF} vni {L3VNI}\n!\n"
    c += f"ip virtual-router mac-address {VMAC}\n!\nip routing\nip routing vrf {VRF}\n!\n"
    c += LOOP_POLICY
    if is_border:
        c += f"""ip prefix-list PL-FROM-WAN seq 10 permit 0.0.0.0/0
ip prefix-list PL-TENANT seq 10 permit 10.10.0.0/16 le 24
!
route-map RM-WAN-IN permit 10
   match ip address prefix-list PL-FROM-WAN
!
route-map RM-WAN-OUT permit 10
   match ip address prefix-list PL-TENANT
!
"""

    c += f"router bgp {asn}\n   router-id {lo0(n)}\n   no bgp default ipv4-unicast\n"
    c += paths(mode)
    c += f"""   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY remote-as {SPINE_ASN}
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN remote-as {SPINE_ASN}
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community extended
   neighbor EVPN maximum-routes 0
"""
    c += tuning(mode, ["UNDERLAY"])
    for sname, sd in SPINES.items():
        s_ip, _ = p2p(sd["sid"], d["idx"])
        c += f"   neighbor {s_ip} peer group UNDERLAY\n   neighbor {s_ip} description {sname}\n"
    for sname, sd in SPINES.items():
        c += (f"   neighbor {lo0(sd['n'])} peer group EVPN\n"
              f"   neighbor {lo0(sd['n'])} description {sname}-evpn\n")
    c += "   redistribute connected route-map RM-CONN-2-BGP\n   !\n"
    for v in vlans:
        vni = VLANS[v]["vni"]
        c += (f"   vlan {v}\n      rd {lo0(n)}:{vni}\n"
              f"      route-target both {vni}:{vni}\n      redistribute learned\n   !\n")
    c += "   address-family evpn\n      neighbor EVPN activate\n   !\n"
    c += "   address-family ipv4\n      neighbor UNDERLAY activate\n   !\n"
    c += (f"   vrf {VRF}\n      rd {lo0(n)}:{L3VNI}\n"
          f"      route-target import evpn {L3VNI}:{L3VNI}\n"
          f"      route-target export evpn {L3VNI}:{L3VNI}\n"
          f"      router-id {lo0(n)}\n")
    c += "      " + paths(mode).strip() + "\n"
    if is_border:
        _, _, peer = d["wan"]
        c += (f"      neighbor {peer} remote-as {WAN_ASN}\n"
              f"      neighbor {peer} description wan\n"
              f"      neighbor {peer} route-map RM-WAN-IN in\n"
              f"      neighbor {peer} route-map RM-WAN-OUT out\n"
              f"      neighbor {peer} maximum-routes 1000\n")
        if mode == "solution":
            c += f"      neighbor {peer} bfd\n      neighbor {peer} {BGP_TIMERS}\n"
    c += "      redistribute connected\n"
    if is_border:
        _, _, peer = d["wan"]
        c += f"      !\n      address-family ipv4\n         neighbor {peer} activate\n"
    c += "   !\n!\nend\n"
    return c


def wan(name, d, mode):
    c = header(name, "provider-managed")
    for port, (border, _, ip, _) in sorted(d["links"].items()):
        c += (f"interface Ethernet{port}\n   description CUST_{border}\n"
              f"   no switchport\n   ip address {ip}\n   {BFD_IFACE}\n!\n")
    c += (f"interface Loopback0\n   ip address {d['lo0']}/32\n!\n"
          f"interface Loopback1\n   description internet test target\n"
          f"   ip address {d['target']}/32\n!\nip routing\n!\n"
          f"ip route {d['net']} Null0\n!\n")
    c += f"""router bgp {d['asn']}
   router-id {d['lo0']}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
"""
    for _, (border, asn, _, peer) in sorted(d["links"].items()):
        c += (f"   neighbor {peer} remote-as {asn}\n"
              f"   neighbor {peer} description {border}\n"
              f"   neighbor {peer} default-originate\n"
              f"   neighbor {peer} bfd\n"
              f"   neighbor {peer} {BGP_TIMERS}\n"
              f"   neighbor {peer} maximum-routes 1000\n")
    c += f"   network {d['net']}\n   !\n   address-family ipv4\n"
    for _, (_, _, _, peer) in sorted(d["links"].items()):
        c += f"      neighbor {peer} activate\n"
    return c + "!\nend\n"


def host(name, d):
    c = header(name, "endpoint")
    c += (f"! {name} -> {d['to']}\n!\nspanning-tree mode none\n!\n"
          f"interface Ethernet1\n   description UPLINK\n   no switchport\n"
          f"   ip address {d['ip']}\n!\n"
          f"ip routing\n!\nip route 0.0.0.0/0 {d['gw']}\n!\nend\n")
    return c


def main():
    root = Path(__file__).resolve().parent.parent
    for mode in ("base", "solution"):
        out = root / "configs" / mode
        out.mkdir(parents=True, exist_ok=True)
        for s, d in SPINES.items():
            (out / f"{s}.cfg").write_text(spine(s, d, mode))
        for l, d in LEAVES.items():
            (out / f"{l}.cfg").write_text(leaf(l, d, mode))
        (out / "wan.cfg").write_text(wan("wan", WAN, mode))
        for h, d in HOSTS.items():
            (out / f"{h}.cfg").write_text(host(h, d))
    print("rendered configs/{base,solution}")


if __name__ == "__main__":
    main()
