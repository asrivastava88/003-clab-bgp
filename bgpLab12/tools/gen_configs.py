#!/usr/bin/env python3
"""
bgp-lab12 config renderer (stdlib only).

A rail-optimized AI/HPC fabric. No EVPN, no VXLAN, no VRFs, no overlay of
any kind. Pure routed Clos, BGP all the way down to the server.

Why it looks like this:

  rail-optimized  every server has one NIC per rail, and each rail is its
                  own switch. Two endpoints on the SAME rail index talk in
                  one hop and never touch a spine. That is the entire point
                  of the topology: collectives that stay on-rail get the
                  short path.
  BGP on the host every server runs eBGP to both rails and advertises its
                  own endpoint address. A NIC failure becomes a routing
                  withdrawal in under a second instead of an ARP timeout.
  no overlay      one tenant, no VM mobility, no need for L2 adjacency.
                  An overlay would add encapsulation latency and hide
                  entropy from the hash for no benefit.
  shared ASNs     both rails share one ASN and both spines share another.
                  That makes every equal-length path identical in content
                  too, so standard multipath works without relaxing the
                  AS-path comparison. Part D asks what changes if you give
                  each rail its own ASN.

The thing this fabric is sensitive to is not reachability. It is WIDTH.
A collective finishes when its slowest rank finishes, so losing one of N
equal paths does not break anything, it just makes the whole job slower.
Every fault in this lab is a width fault or a partial-reachability fault.
"""
from pathlib import Path

SPINE_ASN, RAIL_ASN, STOR_ASN = 65100, 65101, 65103
ECMP = 8
MTU = 9214

SPINES = {"spine1": {"sid": 1, "n": 1}, "spine2": {"sid": 2, "n": 2}}
# idx = the spine port this leaf lands on
LEAVES = {
    "rail1": {"asn": RAIL_ASN, "n": 11, "idx": 1, "rid": 1, "kind": "rail"},
    "rail2": {"asn": RAIL_ASN, "n": 12, "idx": 2, "rid": 2, "kind": "rail"},
    "stor1": {"asn": STOR_ASN, "n": 13, "idx": 3, "rid": 3, "kind": "storage"},
}
# every GPU server lands on the same port number on each rail
SERVERS = {
    "gpu1": {"asn": 65201, "n": 21, "ep": "10.10.0.1", "slot": 1, "attach": ["rail1", "rail2"]},
    "gpu2": {"asn": 65202, "n": 22, "ep": "10.10.0.2", "slot": 2, "attach": ["rail1", "rail2"]},
    "gpu3": {"asn": 65203, "n": 23, "ep": "10.10.0.3", "slot": 3, "attach": ["rail1", "rail2"]},
    "nfs1": {"asn": 65204, "n": 24, "ep": "10.20.0.1", "slot": 1, "attach": ["stor1"]},
}
SERVER_PORT_BASE = 2   # leaf Ethernet(SERVER_PORT_BASE + slot) faces a server


def lo0(n): return f"10.0.0.{n}"
def p2p_fabric(sid, idx):
    b = (idx - 1) * 2
    return f"10.1.{sid}.{b}", f"10.1.{sid}.{b+1}"
def p2p_server(rid, slot):
    b = (slot - 1) * 2
    return f"10.2.{rid}.{b}", f"10.2.{rid}.{b+1}"


def header(h, role):
    return f"""! {h} | bgp-lab12 | {role} | generated by tools/gen_configs.py
hostname {h}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode none
!
"""


ADV = """ip prefix-list PL-ADVERTISE seq 10 permit 10.0.0.0/24 eq 32
ip prefix-list PL-ADVERTISE seq 20 permit 10.10.0.0/16 eq 32
ip prefix-list PL-ADVERTISE seq 30 permit 10.20.0.0/16 eq 32
!
route-map RM-ADVERTISE permit 10
   match ip address prefix-list PL-ADVERTISE
!
"""


def bgp_head(asn, rid):
    return f"""router bgp {asn}
   router-id {rid}
   no bgp default ipv4-unicast
   distance bgp 20 200 200
   maximum-paths {ECMP} ecmp {ECMP}
"""


def iface(port, desc, ip):
    return (f"interface Ethernet{port}\n   description {desc}\n"
            f"   no switchport\n   mtu {MTU}\n   ip address {ip}\n!\n")


def spine(name, d):
    c = header(name, "spine")
    for lf, ld in LEAVES.items():
        s, _ = p2p_fabric(d["sid"], ld["idx"])
        c += iface(ld["idx"], f"P2P_{lf}", f"{s}/31")
    c += f"interface Loopback0\n   ip address {lo0(d['n'])}/32\n!\nip routing\n!\n" + ADV
    c += bgp_head(SPINE_ASN, lo0(d["n"]))
    c += ("   neighbor FABRIC peer group\n   neighbor FABRIC send-community\n"
          "   neighbor FABRIC maximum-routes 12000\n")
    for lf, ld in LEAVES.items():
        _, l = p2p_fabric(d["sid"], ld["idx"])
        c += (f"   neighbor {l} peer group FABRIC\n   neighbor {l} remote-as {ld['asn']}\n"
              f"   neighbor {l} description {lf}\n")
    c += ("   redistribute connected route-map RM-ADVERTISE\n   !\n"
          "   address-family ipv4\n      neighbor FABRIC activate\n!\nend\n")
    return c


def leaf(name, d):
    c = header(name, d["kind"])
    for sn, sd in SPINES.items():
        _, l = p2p_fabric(sd["sid"], d["idx"])
        c += iface(sd["sid"], f"P2P_{sn}", f"{l}/31")
    mine = {s: sd for s, sd in SERVERS.items() if name in sd["attach"]}
    for s, sd in mine.items():
        port = SERVER_PORT_BASE + sd["slot"]
        r, _ = p2p_server(d["rid"], sd["slot"])
        c += iface(port, f"SERVER_{s}", f"{r}/31")
    c += f"interface Loopback0\n   ip address {lo0(d['n'])}/32\n!\nip routing\n!\n" + ADV
    c += bgp_head(d["asn"], lo0(d["n"]))
    c += ("   neighbor FABRIC peer group\n"
          f"   neighbor FABRIC remote-as {SPINE_ASN}\n"
          "   neighbor FABRIC send-community\n   neighbor FABRIC maximum-routes 12000\n"
          "   neighbor SERVERS peer group\n   neighbor SERVERS send-community\n"
          "   neighbor SERVERS maximum-routes 100\n")
    for sn, sd in SPINES.items():
        s, _ = p2p_fabric(sd["sid"], d["idx"])
        c += f"   neighbor {s} peer group FABRIC\n   neighbor {s} description {sn}\n"
    for s, sd in mine.items():
        _, srv = p2p_server(d["rid"], sd["slot"])
        c += (f"   neighbor {srv} peer group SERVERS\n   neighbor {srv} remote-as {sd['asn']}\n"
              f"   neighbor {srv} description {s}\n")
    c += ("   redistribute connected route-map RM-ADVERTISE\n   !\n"
          "   address-family ipv4\n      neighbor FABRIC activate\n"
          "      neighbor SERVERS activate\n!\nend\n")
    return c


def server(name, d):
    """A compute node that speaks BGP. Its endpoint address lives on a
    loopback, not on a NIC, so losing a NIC costs a path and not an address."""
    c = header(name, "compute node, runs BGP")
    peers = []
    for i, rail in enumerate(d["attach"], start=1):
        rd = LEAVES[rail]
        r, srv = p2p_server(rd["rid"], d["slot"])
        c += iface(i, f"NIC{i}_to_{rail}", f"{srv}/31")
        peers.append((r, rail, rd["asn"]))
    c += (f"interface Loopback0\n   description ROUTER_ID\n   ip address {lo0(d['n'])}/32\n!\n"
          f"interface Loopback1\n   description COMPUTE_ENDPOINT\n   ip address {d['ep']}/32\n!\n"
          f"ip routing\n!\n" + ADV)
    c += bgp_head(d["asn"], lo0(d["n"]))
    c += ("   neighbor RAILS peer group\n   neighbor RAILS send-community\n"
          "   neighbor RAILS maximum-routes 12000\n")
    for ip, rail, asn in peers:
        c += (f"   neighbor {ip} peer group RAILS\n   neighbor {ip} remote-as {asn}\n"
              f"   neighbor {ip} description {rail}\n")
    c += ("   redistribute connected route-map RM-ADVERTISE\n   !\n"
          "   address-family ipv4\n      neighbor RAILS activate\n!\nend\n")
    return c


def main():
    out = Path(__file__).resolve().parent.parent / "configs" / "solution"
    out.mkdir(parents=True, exist_ok=True)
    for s, d in SPINES.items():
        (out / f"{s}.cfg").write_text(spine(s, d))
    for l, d in LEAVES.items():
        (out / f"{l}.cfg").write_text(leaf(l, d))
    for s, d in SERVERS.items():
        (out / f"{s}.cfg").write_text(server(s, d))
    print("rendered configs/solution")


if __name__ == "__main__":
    main()
