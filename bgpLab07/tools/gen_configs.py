#!/usr/bin/env python3
"""
bgp-lab07 config renderer (stdlib only).

Multi-VRF EVPN-VXLAN. Four VRFs and two different ways to connect them:

  RT leaking      tenant <-> SHARED services, done purely with asymmetric
                  route-target import/export. No device in the path.
  fusion          RED <-> BLUE, forced across an external device (fw) so the
                  traffic can be inspected.
  isolation       GREEN reaches SHARED and nothing else. Nobody reaches GREEN.

The import/export matrix below IS the policy. Read it as the security document,
because that is what it is.

Modes:
  base      fabric, EVPN overlay, all four VRFs, every VRF importing only its
            own RT. Total isolation, no shared services, no fusion.
  solution  the full matrix plus the fusion handoff.
"""
from pathlib import Path

# ============================ DATA ============================
SPINE_ASN = 65100
FW_ASN = 65200
VMAC = "00:1c:73:00:00:99"

# ---- the policy matrix ----
# export: the RT this VRF stamps on routes it originates
# imports: every RT this VRF accepts. A tenant importing another tenant's RT
#          is an isolation breach, which is exactly ticket 1.
VRFS = {
    "RED":    {"l3vni": 50001, "export": "50001:50001",
               "imports": ["50001:50001", "50099:50099"], "fusion": True},
    "BLUE":   {"l3vni": 50002, "export": "50002:50002",
               "imports": ["50002:50002", "50099:50099"], "fusion": True},
    "GREEN":  {"l3vni": 50003, "export": "50003:50003",
               "imports": ["50003:50003", "50099:50099"], "fusion": False},
    "SHARED": {"l3vni": 50099, "export": "50099:50099",
               "imports": ["50099:50099", "50001:50001",
                           "50002:50002", "50003:50003"], "fusion": False},
}
# the hub is SHARED: it imports every spoke, every spoke imports only the hub

VLANS = {
    10:  {"name": "RED_WEB",   "vrf": "RED",    "gw": "10.10.10.1/24",   "vni": 10010},
    11:  {"name": "RED_APP",   "vrf": "RED",    "gw": "10.10.11.1/24",   "vni": 10011},
    20:  {"name": "BLUE_WEB",  "vrf": "BLUE",   "gw": "10.20.20.1/24",   "vni": 10020},
    30:  {"name": "GREEN_WEB", "vrf": "GREEN",  "gw": "10.30.30.1/24",   "vni": 10030},
    100: {"name": "SVC",       "vrf": "SHARED", "gw": "10.100.100.1/24", "vni": 10100},
}

SPINES = {"spine1": {"sid": 1, "n": 1}, "spine2": {"sid": 2, "n": 2}}

LEAVES = {
    # VLAN 10 is stretched across leaf1 and leaf2, so there is a real L2VNI to test
    "leaf1":  {"asn": 65101, "n": 11, "idx": 1,
               "vlans": [10, 11, 20],
               "access": {3: (10, "hR1"), 4: (20, "hB1")}},
    "leaf2":  {"asn": 65102, "n": 12, "idx": 2,
               "vlans": [10, 30, 100],
               "access": {3: (10, "hR2"), 4: (30, "hG1"), 5: (100, "hS1")}},
    "bleaf1": {"asn": 65104, "n": 14, "idx": 3,
               "vlans": [], "access": {},
               # one physical link to fw, one dot1q subinterface per fused VRF
               "fusion_port": 3,
               "fusion": {"RED":  (101, "172.16.1.1/30", "172.16.1.2"),
                          "BLUE": (102, "172.16.2.1/30", "172.16.2.2")}},
}

HOSTS = {
    "hR1": {"ip": "10.10.10.101/24", "gw": "10.10.10.1",   "to": "leaf1 vlan 10 (RED)"},
    "hB1": {"ip": "10.20.20.101/24", "gw": "10.20.20.1",   "to": "leaf1 vlan 20 (BLUE)"},
    "hR2": {"ip": "10.10.10.102/24", "gw": "10.10.10.1",   "to": "leaf2 vlan 10 (RED, stretched)"},
    "hG1": {"ip": "10.30.30.101/24", "gw": "10.30.30.1",   "to": "leaf2 vlan 30 (GREEN)"},
    "hS1": {"ip": "10.100.100.10/24", "gw": "10.100.100.1", "to": "leaf2 vlan 100 (SHARED services)"},
}

# what the fusion device is allowed to pass between RED and BLUE
FUSION_NETS = {"RED": "10.10.0.0/16", "BLUE": "10.20.0.0/16"}
# ==============================================================


def lo0(n):
    return f"10.0.0.{n}"


def lo1(n):
    return f"10.0.1.{n}"


def p2p(sid, idx):
    b = (idx - 1) * 2
    return f"10.1.{sid}.{b}", f"10.1.{sid}.{b + 1}"


def header(host, mode):
    return f"""! {host} | bgp-lab07 | {mode} | generated by tools/gen_configs.py
hostname {host}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode mstp
!
"""


LOOP_POLICY = """ip prefix-list PL-LOOPBACKS seq 10 permit 10.0.0.0/24 eq 32
ip prefix-list PL-LOOPBACKS seq 20 permit 10.0.1.0/24 eq 32
!
route-map RM-CONN-2-BGP permit 10
   match ip address prefix-list PL-LOOPBACKS
!
"""


def spine(name, d, mode):
    c = header(name, mode)
    for leaf, ld in LEAVES.items():
        s_ip, _ = p2p(d["sid"], ld["idx"])
        c += (f"interface Ethernet{ld['idx']}\n   description P2P_{leaf}\n"
              f"   no switchport\n   mtu 9214\n   ip address {s_ip}/31\n!\n")
    c += f"interface Loopback0\n   ip address {lo0(d['n'])}/32\n!\nip routing\n!\n" + LOOP_POLICY
    c += f"""router bgp {SPINE_ASN}
   router-id {lo0(d['n'])}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN next-hop-unchanged
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community extended
   neighbor EVPN maximum-routes 0
"""
    for leaf, ld in LEAVES.items():
        _, l_ip = p2p(d["sid"], ld["idx"])
        c += (f"   neighbor {l_ip} peer group UNDERLAY\n"
              f"   neighbor {l_ip} remote-as {ld['asn']}\n"
              f"   neighbor {l_ip} description {leaf}\n")
    for leaf, ld in LEAVES.items():
        c += (f"   neighbor {lo0(ld['n'])} peer group EVPN\n"
              f"   neighbor {lo0(ld['n'])} remote-as {ld['asn']}\n"
              f"   neighbor {lo0(ld['n'])} description {leaf}-evpn\n")
    c += """   redistribute connected route-map RM-CONN-2-BGP
   !
   address-family evpn
      neighbor EVPN activate
   !
   address-family ipv4
      neighbor UNDERLAY activate
!
end
"""
    return c


def fusion_policy():
    return f"""ip prefix-list PL-RED seq 10 permit {FUSION_NETS['RED']} le 24
!
ip prefix-list PL-BLUE seq 10 permit {FUSION_NETS['BLUE']} le 24
!
route-map RM-RED-OUT permit 10
   description hand RED's own prefixes to the fusion device
   match ip address prefix-list PL-RED
!
route-map RM-RED-IN permit 10
   description accept only BLUE's prefixes back into RED
   match ip address prefix-list PL-BLUE
!
route-map RM-BLUE-OUT permit 10
   match ip address prefix-list PL-BLUE
!
route-map RM-BLUE-IN permit 10
   match ip address prefix-list PL-RED
!
"""


def leaf(name, d, mode):
    n, asn = d["n"], d["asn"]
    vlans = sorted(d["vlans"])
    is_border = "fusion" in d
    # which VRFs this device needs to instantiate
    if is_border:
        local_vrfs = [v for v in VRFS if VRFS[v]["fusion"]]
    else:
        local_vrfs = sorted({VLANS[v]["vrf"] for v in vlans})

    c = header(name, mode)
    for v in vlans:
        c += f"vlan {v}\n   name {VLANS[v]['name']}\n!\n"
    for vrf in local_vrfs:
        c += f"vrf instance {vrf}\n!\n"

    for sname, sd in SPINES.items():
        _, l_ip = p2p(sd["sid"], d["idx"])
        c += (f"interface Ethernet{sd['sid']}\n   description P2P_{sname}\n"
              f"   no switchport\n   mtu 9214\n   ip address {l_ip}/31\n!\n")

    for port, (v, h) in sorted(d["access"].items()):
        c += (f"interface Ethernet{port}\n   description HOST_{h}_{VLANS[v]['vrf']}\n"
              f"   switchport access vlan {v}\n   spanning-tree portfast\n"
              f"   spanning-tree bpduguard enable\n!\n")

    if is_border:
        fp = d["fusion_port"]
        c += (f"interface Ethernet{fp}\n   description FUSION_fw\n   no switchport\n!\n")
        if mode == "solution":
            for vrf, (tag, ip, _) in d["fusion"].items():
                c += (f"interface Ethernet{fp}.{tag}\n   description FUSION_fw_vrf_{vrf}\n"
                      f"   encapsulation dot1q vlan {tag}\n   vrf {vrf}\n"
                      f"   ip address {ip}\n!\n")

    c += (f"interface Loopback0\n   description ROUTER_ID_EVPN\n   ip address {lo0(n)}/32\n!\n"
          f"interface Loopback1\n   description VTEP\n   ip address {lo1(n)}/32\n!\n")

    for v in vlans:
        c += (f"interface Vlan{v}\n   description {VLANS[v]['name']}\n"
              f"   vrf {VLANS[v]['vrf']}\n   ip address virtual {VLANS[v]['gw']}\n!\n")

    c += "interface Vxlan1\n   vxlan source-interface Loopback1\n   vxlan udp-port 4789\n"
    for v in vlans:
        c += f"   vxlan vlan {v} vni {VLANS[v]['vni']}\n"
    for vrf in local_vrfs:
        c += f"   vxlan vrf {vrf} vni {VRFS[vrf]['l3vni']}\n"
    c += f"!\nip virtual-router mac-address {VMAC}\n!\nip routing\n"
    for vrf in local_vrfs:
        c += f"ip routing vrf {vrf}\n"
    c += "!\n" + LOOP_POLICY
    if is_border and mode == "solution":
        c += fusion_policy()

    c += f"""router bgp {asn}
   router-id {lo0(n)}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY remote-as {SPINE_ASN}
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN remote-as {SPINE_ASN}
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community extended
   neighbor EVPN maximum-routes 0
"""
    for sname, sd in SPINES.items():
        s_ip, _ = p2p(sd["sid"], d["idx"])
        c += f"   neighbor {s_ip} peer group UNDERLAY\n   neighbor {s_ip} description {sname}\n"
    for sname, sd in SPINES.items():
        c += (f"   neighbor {lo0(sd['n'])} peer group EVPN\n"
              f"   neighbor {lo0(sd['n'])} description {sname}-evpn\n")
    c += "   redistribute connected route-map RM-CONN-2-BGP\n   !\n"

    for v in vlans:
        vni = VLANS[v]["vni"]
        c += (f"   vlan {v}\n      rd {lo0(n)}:{vni}\n"
              f"      route-target both {vni}:{vni}\n      redistribute learned\n   !\n")
    c += "   address-family evpn\n      neighbor EVPN activate\n   !\n"
    c += "   address-family ipv4\n      neighbor UNDERLAY activate\n   !\n"

    for vrf in local_vrfs:
        vd = VRFS[vrf]
        c += f"   vrf {vrf}\n      rd {lo0(n)}:{vd['l3vni']}\n"
        if mode == "base":
            # isolation only: a VRF sees nothing but itself
            c += (f"      route-target import evpn {vd['export']}\n"
                  f"      route-target export evpn {vd['export']}\n")
        else:
            for rt in vd["imports"]:
                c += f"      route-target import evpn {rt}\n"
            c += f"      route-target export evpn {vd['export']}\n"
        c += f"      router-id {lo0(n)}\n      maximum-paths 4 ecmp 4\n"
        if is_border and mode == "solution" and vrf in d["fusion"]:
            _, _, peer = d["fusion"][vrf]
            c += (f"      neighbor {peer} remote-as {FW_ASN}\n"
                  f"      neighbor {peer} description fw-{vrf}\n"
                  f"      neighbor {peer} route-map RM-{vrf}-IN in\n"
                  f"      neighbor {peer} route-map RM-{vrf}-OUT out\n"
                  f"      neighbor {peer} maximum-routes 1000\n")
        c += "      redistribute connected\n"
        if is_border and mode == "solution" and vrf in d["fusion"]:
            _, _, peer = d["fusion"][vrf]
            c += f"      !\n      address-family ipv4\n         neighbor {peer} activate\n"
        c += "   !\n"
    return c + "!\nend\n"


def fw(name, mode):
    """The fusion device. One physical link to bleaf1, one subinterface per
    fused VRF. It is the only path between RED and BLUE, which is the point:
    put a firewall here and inter-tenant traffic is inspectable."""
    c = header(name, "fusion-device")
    c += "interface Ethernet1\n   description FUSION_bleaf1\n   no switchport\n!\n"
    for vrf, (tag, _, ip) in LEAVES["bleaf1"]["fusion"].items():
        c += (f"interface Ethernet1.{tag}\n   description FUSION_bleaf1_vrf_{vrf}\n"
              f"   encapsulation dot1q vlan {tag}\n   ip address {ip}/30\n!\n")
    c += "interface Loopback0\n   description ROUTER_ID\n   ip address 10.255.200.1/32\n!\nip routing\n!\n"
    c += f"""ip prefix-list PL-RED seq 10 permit {FUSION_NETS['RED']} le 24
!
ip prefix-list PL-BLUE seq 10 permit {FUSION_NETS['BLUE']} le 24
!
route-map RM-FROM-RED permit 10
   match ip address prefix-list PL-RED
!
route-map RM-FROM-BLUE permit 10
   match ip address prefix-list PL-BLUE
!
route-map RM-TO-RED permit 10
   description only BLUE's prefixes go back toward RED
   match ip address prefix-list PL-BLUE
!
route-map RM-TO-BLUE permit 10
   match ip address prefix-list PL-RED
!
router bgp {FW_ASN}
   router-id 10.255.200.1
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
"""
    for vrf, (_, _, _) in LEAVES["bleaf1"]["fusion"].items():
        tag, b_ip, _ = LEAVES["bleaf1"]["fusion"][vrf]
        peer = b_ip.split("/")[0]
        other = "BLUE" if vrf == "RED" else "RED"
        c += (f"   neighbor {peer} remote-as {LEAVES['bleaf1']['asn']}\n"
              f"   neighbor {peer} description bleaf1-{vrf}\n"
              f"   neighbor {peer} route-map RM-FROM-{vrf} in\n"
              f"   neighbor {peer} route-map RM-TO-{vrf} out\n"
              f"   neighbor {peer} maximum-routes 1000\n"
              f"   ! the fabric AS appears in the path on the way back, so strip\n"
              f"   ! the private ASNs or bleaf1 drops its own routes as a loop\n"
              f"   neighbor {peer} remove-private-as all\n")
    c += "   !\n   address-family ipv4\n"
    for vrf in LEAVES["bleaf1"]["fusion"]:
        peer = LEAVES["bleaf1"]["fusion"][vrf][1].split("/")[0]
        c += f"      neighbor {peer} activate\n"
    return c + "!\nend\n"


def host(name, d):
    c = header(name, "endpoint")
    c += (f"! {name} -> {d['to']}\n!\nspanning-tree mode none\n!\n"
          f"interface Ethernet1\n   description UPLINK\n   no switchport\n"
          f"   ip address {d['ip']}\n!\n"
          f"ip routing\n!\nip route 0.0.0.0/0 {d['gw']}\n!\nend\n")
    return c


def main():
    root = Path(__file__).resolve().parent.parent
    for mode in ("base", "solution"):
        out = root / "configs" / mode
        out.mkdir(parents=True, exist_ok=True)
        for s, d in SPINES.items():
            (out / f"{s}.cfg").write_text(spine(s, d, mode))
        for l, d in LEAVES.items():
            (out / f"{l}.cfg").write_text(leaf(l, d, mode))
        (out / "fw.cfg").write_text(fw("fw", mode))
        for h, d in HOSTS.items():
            (out / f"{h}.cfg").write_text(host(h, d))
    print("rendered configs/{base,solution}")


if __name__ == "__main__":
    main()
