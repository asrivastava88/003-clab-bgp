#!/usr/bin/env python3
"""
bgp-lab04 config renderer (stdlib only).

Design, and the whole point of the lab: ONE autonomous system.
  underlay : OSPF area 0 on /31 point-to-point links, loopbacks advertised
  overlay  : iBGP EVPN, spines are route reflectors, clients peer Lo0 to Lo0
  egress   : two border leaves, each eBGP to wan (AS 65100) inside VRF RED

Modes:
  base      OSPF underlay + VLAN/SVI/VXLAN/VRF scaffolding. NO BGP anywhere.
            You build the whole overlay.
  solution  iBGP RR overlay complete, border eBGP complete, NO add-path.
            Clients see one default: the RR hides the second path.
  addpath   solution + add-path, so clients see both borders and ECMP out.
"""
from pathlib import Path

# ============================ DATA ============================
FABRIC_ASN = 65000          # every fabric device, hence iBGP
WAN_ASN = 65100
VMAC = "00:1c:73:00:00:99"
VRF, L3VNI = "RED", 50001

VLANS = {
    10: {"name": "APP", "gw": "10.10.10.1/24", "vni": 10010},
    20: {"name": "DB",  "gw": "10.10.20.1/24", "vni": 10020},
}

SPINES = {"spine1": {"sid": 1, "n": 1}, "spine2": {"sid": 2, "n": 2}}

# idx = the spine port this device lands on, and its /31 slot
LEAVES = {
    "leaf1":  {"n": 11, "idx": 1, "vlans": [10],     "access": {3: (10, "h1")}},
    "leaf2":  {"n": 12, "idx": 2, "vlans": [10, 20], "access": {3: (10, "h2"), 4: (20, "h3")}},
    "bleaf1": {"n": 14, "idx": 3, "vlans": [], "access": {},
               "wan": (3, "172.16.1.1/30", "172.16.1.2")},
    "bleaf2": {"n": 15, "idx": 4, "vlans": [], "access": {},
               "wan": (3, "172.16.2.1/30", "172.16.2.2")},
}

WAN = {"asn": WAN_ASN, "lo0": "10.255.0.1", "target": "203.0.113.10",
       "net": "203.0.113.0/24",
       # port: (border, wan_ip, border_ip)
       "links": {1: ("bleaf1", "172.16.1.2/30", "172.16.1.1"),
                 2: ("bleaf2", "172.16.2.2/30", "172.16.2.1")}}

HOSTS = {
    "h1": {"ip": "10.10.10.101/24", "gw": "10.10.10.1", "to": "leaf1 vlan 10"},
    "h2": {"ip": "10.10.10.102/24", "gw": "10.10.10.1", "to": "leaf2 vlan 10"},
    "h3": {"ip": "10.10.20.103/24", "gw": "10.10.20.1", "to": "leaf2 vlan 20"},
}

TENANT_SUPERNET = "10.10.0.0/16"
# ==============================================================


def lo0(n):
    return f"10.0.0.{n}"


def lo1(n):
    return f"10.0.1.{n}"


def p2p(sid, idx):
    """spine side even, leaf side odd, inside 10.1.<sid>.0/24"""
    b = (idx - 1) * 2
    return f"10.1.{sid}.{b}", f"10.1.{sid}.{b + 1}"


def header(host, mode):
    return f"""! {host} | bgp-lab04 | {mode} | generated by tools/gen_configs.py
hostname {host}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode mstp
!
"""


def ospf(rid, fabric_ports):
    """Underlay. The loopbacks come from OSPF, which is why no fabric device
    needs 'redistribute connected' into BGP the way labs 01-03 did."""
    c = f"router ospf 1\n   router-id {rid}\n   passive-interface default\n"
    for p in fabric_ports:
        c += f"   no passive-interface Ethernet{p}\n"
    c += ("   network 10.0.0.0/16 area 0.0.0.0\n"
          "   network 10.1.0.0/16 area 0.0.0.0\n"
          "   max-lsa 12000\n!\n")
    return c


def spine(name, d, mode):
    c = header(name, mode)
    ports = []
    for leaf, ld in LEAVES.items():
        s_ip, _ = p2p(d["sid"], ld["idx"])
        ports.append(ld["idx"])
        c += (f"interface Ethernet{ld['idx']}\n   description P2P_{leaf}\n"
              f"   no switchport\n   mtu 9214\n   ip address {s_ip}/31\n"
              f"   ip ospf network point-to-point\n!\n")
    c += f"interface Loopback0\n   description ROUTER_ID_AND_OVERLAY_PEERING\n   ip address {lo0(d['n'])}/32\n!\n"
    c += "ip routing\n!\n" + ospf(lo0(d["n"]), sorted(ports))
    if mode == "base":
        return c + "end\n"

    # A spine here is a route reflector only. No VTEP, no VRF, not in the
    # VXLAN data path, and it must never rewrite an EVPN next hop.
    c += f"""router bgp {FABRIC_ASN}
   router-id {lo0(d['n'])}
   no bgp default ipv4-unicast
   distance bgp 20 200 200
   neighbor OVERLAY peer group
   neighbor OVERLAY remote-as {FABRIC_ASN}
   neighbor OVERLAY update-source Loopback0
   neighbor OVERLAY route-reflector-client
   neighbor OVERLAY send-community extended
   neighbor OVERLAY maximum-routes 0
"""
    for leaf, ld in LEAVES.items():
        c += (f"   neighbor {lo0(ld['n'])} peer group OVERLAY\n"
              f"   neighbor {lo0(ld['n'])} description {leaf}\n")
    c += "   !\n   address-family evpn\n      neighbor OVERLAY activate\n"
    if mode == "addpath":
        c += ("      ! without these the reflector advertises one best path per\n"
              "      ! prefix and the second border leaf is invisible to clients\n"
              "      bgp additional-paths send any\n"
              "      bgp additional-paths receive\n")
    return c + "!\nend\n"


def border_policy():
    return f"""ip prefix-list PL-FROM-WAN seq 10 permit 0.0.0.0/0
ip prefix-list PL-FROM-WAN seq 20 permit 203.0.113.0/24
ip prefix-list PL-TENANT seq 10 permit {TENANT_SUPERNET} le 24
!
route-map RM-WAN-IN permit 10
   match ip address prefix-list PL-FROM-WAN
!
route-map RM-WAN-OUT permit 10
   match ip address prefix-list PL-TENANT
!
"""


def leaf(name, d, mode):
    n = d["n"]
    vlans = sorted(d["vlans"])
    is_border = "wan" in d
    c = header(name, mode)
    for v in vlans:
        c += f"vlan {v}\n   name {VLANS[v]['name']}\n!\n"
    c += f"vrf instance {VRF}\n!\n"

    ports = []
    for sname, sd in SPINES.items():
        _, l_ip = p2p(sd["sid"], d["idx"])
        ports.append(sd["sid"])
        c += (f"interface Ethernet{sd['sid']}\n   description P2P_{sname}\n"
              f"   no switchport\n   mtu 9214\n   ip address {l_ip}/31\n"
              f"   ip ospf network point-to-point\n!\n")

    for port, (v, h) in sorted(d["access"].items()):
        c += (f"interface Ethernet{port}\n   description HOST_{h}\n"
              f"   switchport access vlan {v}\n   spanning-tree portfast\n"
              f"   spanning-tree bpduguard enable\n!\n")

    if is_border:
        port, b_ip, _ = d["wan"]
        c += (f"interface Ethernet{port}\n   description WAN_vrf_{VRF}\n"
              f"   no switchport\n   vrf {VRF}\n   ip address {b_ip}\n!\n")

    c += (f"interface Loopback0\n   description ROUTER_ID_AND_OVERLAY_PEERING\n"
          f"   ip address {lo0(n)}/32\n!\n"
          f"interface Loopback1\n   description VTEP\n   ip address {lo1(n)}/32\n!\n")

    for v in vlans:
        c += (f"interface Vlan{v}\n   description {VLANS[v]['name']}\n   vrf {VRF}\n"
              f"   ip address virtual {VLANS[v]['gw']}\n!\n")

    c += "interface Vxlan1\n   vxlan source-interface Loopback1\n   vxlan udp-port 4789\n"
    for v in vlans:
        c += f"   vxlan vlan {v} vni {VLANS[v]['vni']}\n"
    c += f"   vxlan vrf {VRF} vni {L3VNI}\n!\n"
    c += f"ip virtual-router mac-address {VMAC}\n!\nip routing\nip routing vrf {VRF}\n!\n"
    c += ospf(lo0(n), sorted(ports))
    if is_border and mode != "base":
        c += border_policy()
    if mode == "base":
        return c + "end\n"

    c += f"""router bgp {FABRIC_ASN}
   router-id {lo0(n)}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor OVERLAY peer group
   neighbor OVERLAY remote-as {FABRIC_ASN}
   neighbor OVERLAY update-source Loopback0
   neighbor OVERLAY send-community extended
   neighbor OVERLAY maximum-routes 0
"""
    for sname, sd in SPINES.items():
        c += (f"   neighbor {lo0(sd['n'])} peer group OVERLAY\n"
              f"   neighbor {lo0(sd['n'])} description {sname}-rr\n")
    c += "   !\n"
    for v in vlans:
        vni = VLANS[v]["vni"]
        c += (f"   vlan {v}\n      rd {lo0(n)}:{vni}\n"
              f"      route-target both {vni}:{vni}\n      redistribute learned\n   !\n")
    c += "   address-family evpn\n      neighbor OVERLAY activate\n"
    if mode == "addpath":
        c += "      bgp additional-paths receive\n"
    c += "   !\n"
    c += (f"   vrf {VRF}\n      rd {lo0(n)}:{L3VNI}\n"
          f"      route-target import evpn {L3VNI}:{L3VNI}\n"
          f"      route-target export evpn {L3VNI}:{L3VNI}\n"
          f"      router-id {lo0(n)}\n"
          f"      maximum-paths 4 ecmp 4\n")
    if is_border:
        _, _, peer = d["wan"]
        c += (f"      neighbor {peer} remote-as {WAN_ASN}\n"
              f"      neighbor {peer} description wan\n"
              f"      neighbor {peer} route-map RM-WAN-IN in\n"
              f"      neighbor {peer} route-map RM-WAN-OUT out\n"
              f"      neighbor {peer} maximum-routes 1000\n")
    c += "      redistribute connected\n"
    if is_border:
        _, _, peer = d["wan"]
        c += f"      !\n      address-family ipv4\n         neighbor {peer} activate\n"
    c += "   !\n!\nend\n"
    return c


def wan(name, d):
    """Provider-managed. Identical in every mode."""
    c = header(name, "provider-managed")
    peers = []
    for port, (border, w_ip, b_ip) in sorted(d["links"].items()):
        peers.append((b_ip, border))
        c += (f"interface Ethernet{port}\n   description CUST_{border}\n"
              f"   no switchport\n   ip address {w_ip}\n!\n")
    c += (f"interface Loopback0\n   description ROUTER_ID\n   ip address {d['lo0']}/32\n!\n"
          f"interface Loopback1\n   description internet test target\n"
          f"   ip address {d['target']}/32\n!\nip routing\n!\n"
          f"! pull {d['net']} into the table so BGP can originate it\n"
          f"ip route {d['net']} Null0\n!\n"
          f"ip prefix-list PL-TO-CUST seq 10 permit 0.0.0.0/0\n"
          f"ip prefix-list PL-TO-CUST seq 20 permit {d['net']}\n"
          f"ip prefix-list PL-FROM-CUST seq 10 permit {TENANT_SUPERNET} le 24\n!\n"
          f"route-map RM-CUST-IN permit 10\n   match ip address prefix-list PL-FROM-CUST\n!\n"
          f"route-map RM-CUST-OUT permit 10\n   match ip address prefix-list PL-TO-CUST\n!\n")
    c += f"""router bgp {d['asn']}
   router-id {d['lo0']}
   maximum-paths 4 ecmp 4
   neighbor CUSTOMER peer group
   neighbor CUSTOMER remote-as {FABRIC_ASN}
   neighbor CUSTOMER route-map RM-CUST-IN in
   neighbor CUSTOMER route-map RM-CUST-OUT out
   neighbor CUSTOMER default-originate
   neighbor CUSTOMER maximum-routes 100
"""
    for b_ip, border in peers:
        c += f"   neighbor {b_ip} peer group CUSTOMER\n   neighbor {b_ip} description {border}\n"
    c += f"   network {d['net']}\n!\nend\n"
    return c


def host(name, d):
    """Endpoint. STP off: leaf access ports run bpduguard."""
    c = header(name, "endpoint")
    c += (f"! {name} -> {d['to']}\n!\nspanning-tree mode none\n!\n"
          f"interface Ethernet1\n   description UPLINK\n   no switchport\n"
          f"   ip address {d['ip']}\n!\n"
          f"ip routing\n!\nip route 0.0.0.0/0 {d['gw']}\n!\nend\n")
    return c


def main():
    root = Path(__file__).resolve().parent.parent
    for mode in ("base", "solution", "addpath"):
        out = root / "configs" / mode
        out.mkdir(parents=True, exist_ok=True)
        for s, d in SPINES.items():
            (out / f"{s}.cfg").write_text(spine(s, d, mode))
        for l, d in LEAVES.items():
            (out / f"{l}.cfg").write_text(leaf(l, d, mode))
        (out / "wan.cfg").write_text(wan("wan", WAN))
        for h, d in HOSTS.items():
            (out / f"{h}.cfg").write_text(host(h, d))
    print("rendered configs/{base,solution,addpath}")


if __name__ == "__main__":
    main()
