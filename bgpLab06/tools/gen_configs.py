#!/usr/bin/env python3
"""
bgp-lab06 config renderer (stdlib only).

Pure BGP. No EVPN, no VXLAN, no VRFs. A multi-AS internet edge, which is where
the protocol itself actually gets exercised:

  AS 65100 (ours)   core, edge1, edge2    OSPF underlay + iBGP full mesh
  AS 65200 transitA upstream, sends a default
  AS 65300 transitB upstream, sends a default
  AS 65400 peerX    settlement-free peer
  AS 65500 cust1    our customer
  AS 65600 far      a remote network reachable three ways

Modes:
  base      everything up, ZERO policy. We accept and re-announce everything,
            which makes us free transit between our two upstreams. That is the
            state you are fixing.
  solution  the customer / peer / transit policy triangle, community tagging,
            aggregation, prefix filters and session protection.

External ASes are deliberately permissive. You control your policy, not theirs,
and a leak only shows up as a leak if the other side accepts it.
"""
from pathlib import Path

# ============================ DATA ============================
OUR_ASN = 65100
OUR_SUPERNET = "10.100.0.0/16"

# community tags applied on ingress, matched on egress
C_TRANSIT  = f"{OUR_ASN}:100"
C_PEER     = f"{OUR_ASN}:150"
C_CUSTOMER = f"{OUR_ASN}:200"
LP = {"transit": 100, "peer": 150, "customer": 200}

# ---- our AS ----
INTERNAL = {
    "core":  {"lo0": "10.100.0.1",
              # Loopbacks that originate our address space, so there is
              # something real to aggregate
              "originate": {1: "10.100.16.1/20", 2: "10.100.32.1/20",
                            3: "10.100.48.1/20", 4: "10.100.64.1/20"},
              "igp": {1: ("edge1", "10.100.255.0/31", 10),
                      2: ("edge2", "10.100.255.2/31", 30)},
              "ext": {}},
    "edge1": {"lo0": "10.100.0.2", "originate": {},
              "igp": {1: ("core",  "10.100.255.1/31", 10),
                      2: ("edge2", "10.100.255.4/31", 100)},
              "ext": {3: ("transitA", 65200, "172.16.12.1/30", "172.16.12.2", "transit"),
                      4: ("peerX",    65400, "172.16.14.1/30", "172.16.14.2", "peer")}},
    "edge2": {"lo0": "10.100.0.3", "originate": {},
              "igp": {1: ("core",  "10.100.255.3/31", 30),
                      2: ("edge1", "10.100.255.5/31", 100)},
              "ext": {3: ("transitB", 65300, "172.16.13.1/30", "172.16.13.2", "transit"),
                      4: ("cust1",    65500, "172.16.15.1/30", "172.16.15.2", "customer")}},
}

# ---- everyone else: permissive on purpose ----
EXTERNAL = {
    "transitA": {"asn": 65200, "default_originate": True,
                 "originate": {1: "10.200.0.1/16"},
                 "links": {1: ("edge1", "172.16.12.2/30", "172.16.12.1", OUR_ASN),
                           2: ("far",   "172.16.26.1/30", "172.16.26.2", 65600)}},
    "transitB": {"asn": 65300, "default_originate": True,
                 "originate": {1: "10.201.0.1/16"},
                 "links": {1: ("edge2", "172.16.13.2/30", "172.16.13.1", OUR_ASN),
                           2: ("far",   "172.16.36.1/30", "172.16.36.2", 65600)}},
    "peerX":    {"asn": 65400, "default_originate": False,
                 "originate": {1: "10.202.0.1/16"},
                 "links": {1: ("edge1", "172.16.14.2/30", "172.16.14.1", OUR_ASN),
                           2: ("far",   "172.16.46.1/30", "172.16.46.2", 65600)}},
    "cust1":    {"asn": 65500, "default_originate": False,
                 # a /16 plus two more-specifics, so prefix filtering and
                 # prefix limits have something to bite on
                 "originate": {1: "10.5.0.1/16", 2: "10.5.100.1/24", 3: "10.5.101.1/24"},
                 "links": {1: ("edge2", "172.16.15.2/30", "172.16.15.1", OUR_ASN)}},
    "far":      {"asn": 65600, "default_originate": False,
                 "originate": {1: "10.6.0.1/16"},
                 "links": {1: ("transitA", "172.16.26.2/30", "172.16.26.1", 65200),
                           2: ("transitB", "172.16.36.2/30", "172.16.36.1", 65300),
                           3: ("peerX",    "172.16.46.2/30", "172.16.46.1", 65400)}},
}

CUST_PREFIXES = ["10.5.0.0/16"]      # what we will accept from cust1, and only this
# ==============================================================


def header(host, mode):
    return f"""! {host} | bgp-lab06 | {mode} | generated by tools/gen_configs.py
hostname {host}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode none
!
"""


def our_policy():
    """Ingress tags by neighbor type, egress decided by those tags.
    This is the customer / peer / transit triangle, and it is the whole
    reason the community scheme exists."""
    c = f"""ip prefix-list PL-OURS seq 10 permit {OUR_SUPERNET}
!
ip prefix-list PL-CUST1 seq 10 permit {CUST_PREFIXES[0]}
!
ip prefix-list PL-DEFAULT seq 10 permit 0.0.0.0/0
!
ip community-list CL-TRANSIT permit {C_TRANSIT}
ip community-list CL-PEER permit {C_PEER}
ip community-list CL-CUSTOMER permit {C_CUSTOMER}
!
! ---------------- ingress: tag and rank by neighbor type ----------------
route-map RM-FROM-TRANSIT permit 10
   description upstream: lowest preference, tag as transit-learned
   set local-preference {LP['transit']}
   set community {C_TRANSIT} additive
!
route-map RM-FROM-PEER permit 10
   description settlement-free peer: better than transit, tag as peer-learned
   set local-preference {LP['peer']}
   set community {C_PEER} additive
!
route-map RM-FROM-CUSTOMER permit 10
   description customer: best preference, and accept ONLY their prefixes
   match ip address prefix-list PL-CUST1
   set local-preference {LP['customer']}
   set community {C_CUSTOMER} additive
!
! ---------------- egress: default deny, permit only what we may announce ----------------
! To an upstream or a peer we may announce our own space and our customers'.
! Announcing transit- or peer-learned routes would make us free transit.
route-map RM-TO-TRANSIT permit 10
   description our aggregate
   match ip address prefix-list PL-OURS
!
route-map RM-TO-TRANSIT permit 20
   description customer routes, which we are paid to carry
   match community CL-CUSTOMER
!
route-map RM-TO-PEER permit 10
   match ip address prefix-list PL-OURS
!
route-map RM-TO-PEER permit 20
   match community CL-CUSTOMER
!
! A customer gets everything we know. Here, a default is enough.
route-map RM-TO-CUSTOMER permit 10
   match ip address prefix-list PL-DEFAULT
!
route-map RM-TO-CUSTOMER permit 20
   match ip address prefix-list PL-OURS
!
route-map RM-TO-CUSTOMER permit 30
   match community CL-TRANSIT
!
route-map RM-TO-CUSTOMER permit 40
   match community CL-PEER
!
"""
    return c


def internal(name, d, mode):
    c = header(name, mode)
    for port, (peer, ip, cost) in sorted(d["igp"].items()):
        c += (f"interface Ethernet{port}\n   description IGP_{peer}\n"
              f"   no switchport\n   mtu 9214\n   ip address {ip}\n"
              f"   ip ospf network point-to-point\n   ip ospf cost {cost}\n!\n")
    for port, (peer, asn, ip, _, role) in sorted(d["ext"].items()):
        c += (f"interface Ethernet{port}\n   description EBGP_{peer}_AS{asn}_{role}\n"
              f"   no switchport\n   ip address {ip}\n!\n")
    c += f"interface Loopback0\n   description ROUTER_ID_AND_IBGP\n   ip address {d['lo0']}/32\n!\n"
    for n, ip in sorted(d["originate"].items()):
        c += f"interface Loopback{n}\n   description ORIGINATES_{ip}\n   ip address {ip}\n!\n"
    c += "ip routing\n!\n"
    # OSPF carries loopbacks and the internal links. It does NOT carry any
    # external prefix: everything learned by BGP stays in BGP.
    c += (f"router ospf 1\n   router-id {d['lo0']}\n   passive-interface default\n")
    for port in sorted(d["igp"]):
        c += f"   no passive-interface Ethernet{port}\n"
    c += ("   network 10.100.0.0/22 area 0.0.0.0\n"
          "   network 10.100.255.0/24 area 0.0.0.0\n   max-lsa 12000\n!\n")
    if mode == "solution":
        c += our_policy()

    c += f"""router bgp {OUR_ASN}
   router-id {d['lo0']}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor IBGP peer group
   neighbor IBGP remote-as {OUR_ASN}
   neighbor IBGP update-source Loopback0
   neighbor IBGP send-community
   neighbor IBGP maximum-routes 12000
"""
    if d["ext"]:
        # an edge resolves eBGP next hops that core has no route to
        c += "   neighbor IBGP next-hop-self\n"
    for other, od in INTERNAL.items():
        if other == name:
            continue
        c += (f"   neighbor {od['lo0']} peer group IBGP\n"
              f"   neighbor {od['lo0']} description {other}\n")
    for port, (peer, asn, _, peer_ip, role) in sorted(d["ext"].items()):
        c += (f"   neighbor {peer_ip} remote-as {asn}\n"
              f"   neighbor {peer_ip} description {peer}-{role}\n"
              f"   neighbor {peer_ip} send-community\n")
        if mode == "solution":
            rm_in = {"transit": "RM-FROM-TRANSIT", "peer": "RM-FROM-PEER",
                     "customer": "RM-FROM-CUSTOMER"}[role]
            rm_out = {"transit": "RM-TO-TRANSIT", "peer": "RM-TO-PEER",
                      "customer": "RM-TO-CUSTOMER"}[role]
            c += (f"   neighbor {peer_ip} route-map {rm_in} in\n"
                  f"   neighbor {peer_ip} route-map {rm_out} out\n")
            limit = 50 if role == "customer" else 5000
            c += f"   neighbor {peer_ip} maximum-routes {limit}\n"
        else:
            c += f"   neighbor {peer_ip} maximum-routes 12000\n"
    for n, ip in sorted(d["originate"].items()):
        net = ip.split("/")
        base = ".".join(net[0].split(".")[:3]) + ".0"
        c += f"   network {base}/{net[1]}\n"
    if mode == "solution" and d["ext"]:
        c += (f"   ! one prefix leaves this AS, not four. summary-only suppresses\n"
              f"   ! the component /20s toward every neighbor, iBGP included.\n"
              f"   aggregate-address {OUR_SUPERNET} summary-only\n")
    c += "   !\n   address-family ipv4\n      neighbor IBGP activate\n"
    for _, (_, _, _, peer_ip, _) in sorted(d["ext"].items()):
        c += f"      neighbor {peer_ip} activate\n"
    return c + "!\nend\n"


def external(name, d):
    """Someone else's network. Permissive, and identical in both modes."""
    c = header(name, "external-permissive")
    for port, (peer, ip, _, asn) in sorted(d["links"].items()):
        c += (f"interface Ethernet{port}\n   description EBGP_{peer}_AS{asn}\n"
              f"   no switchport\n   ip address {ip}\n!\n")
    lo0 = f"10.255.{d['asn'] - 65000}.1"
    c += f"interface Loopback0\n   description ROUTER_ID\n   ip address {lo0}/32\n!\n"
    for n, ip in sorted(d["originate"].items()):
        c += f"interface Loopback{n}\n   description ORIGINATES_{ip}\n   ip address {ip}\n!\n"
    c += f"""ip routing
!
router bgp {d['asn']}
   router-id {lo0}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
"""
    for _, (peer, _, peer_ip, asn) in sorted(d["links"].items()):
        c += (f"   neighbor {peer_ip} remote-as {asn}\n"
              f"   neighbor {peer_ip} description {peer}\n"
              f"   neighbor {peer_ip} send-community\n"
              f"   neighbor {peer_ip} maximum-routes 12000\n")
        if d["default_originate"] and peer in ("edge1", "edge2"):
            c += f"   neighbor {peer_ip} default-originate\n"
    for n, ip in sorted(d["originate"].items()):
        net = ip.split("/")
        octs = net[0].split(".")
        if net[1] == "16":
            base = f"{octs[0]}.{octs[1]}.0.0"
        else:
            base = ".".join(octs[:3]) + ".0"
        c += f"   network {base}/{net[1]}\n"
    c += "   !\n   address-family ipv4\n"
    for _, (_, _, peer_ip, _) in sorted(d["links"].items()):
        c += f"      neighbor {peer_ip} activate\n"
    return c + "!\nend\n"


def main():
    root = Path(__file__).resolve().parent.parent
    for mode in ("base", "solution"):
        out = root / "configs" / mode
        out.mkdir(parents=True, exist_ok=True)
        for n, d in INTERNAL.items():
            (out / f"{n}.cfg").write_text(internal(n, d, mode))
        for n, d in EXTERNAL.items():
            (out / f"{n}.cfg").write_text(external(n, d))
    print("rendered configs/{base,solution}")


if __name__ == "__main__":
    main()
