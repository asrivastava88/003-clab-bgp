#!/usr/bin/env python3
"""bgp-lab16 render: the model becomes configs and the topology.

One input, two outputs, no hand editing anywhere. If you want the network to
change, you change model/ and re-render. That is the whole discipline, and it
is what makes tools/audit.py meaningful: there is something to audit against.

  render.py            write configs/solution/*.cfg and bgp-lab16.clab.yml
  render.py --stdout <device>   print one config without writing anything
"""
import sys, os, argparse
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from model import build, load

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
OUT = os.path.join(ROOT, "configs", "solution")

HDR = ("! {name} | bgp-lab16 | {role}\n"
       "! GENERATED from model/network.yml + model/policy.yml by tools/render.py\n"
       "! Do not edit this file or the device. Change the model and re-render.\n")
BASE = """hostname {name}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode none
!
"""

def iface(n, desc, v4, mtu, cost=None):
    s = (f"interface {n}\n   description {desc}\n   no switchport\n"
         f"   mtu {mtu}\n   ip address {v4}\n")
    if cost is not None:
        s += f"   ip ospf cost {cost}\n"
    return s + "!\n"

def plist4(name, entries):
    return "".join(f"ip prefix-list {name} seq {i*10} {e}\n"
                   for i, e in enumerate(entries, 1)) + "!\n"


def render_device(plan, name):
    v = plan["devices"][name]
    pol = plan["policy"]
    asn = plan["asn"]
    role = f"AS {asn} backbone, {v['city']}, {'route reflector' if v['is_rr'] else 'RR client'}"
    s = HDR.format(name=name, role=role) + BASE.format(name=name)

    for ifn in sorted(v["interfaces"], key=lambda x: int(x.replace("Ethernet", ""))):
        i = v["interfaces"][ifn]
        if i["kind"] == "bb":
            desc = f"BACKBONE_link{i['link_id']}_to_{i['far']}_cost{i['cost']}"
            s += iface(ifn, desc, i["v4"], i["mtu"], i["cost"])
        else:
            desc = f"HANDOFF_link{i['link_id']}_{i['ext_kind']}_{i['far']}_AS{i['peer_asn']}"
            s += iface(ifn, desc, i["v4"], i["mtu"])

    s += (f"interface Loopback0\n   description ROUTER_ID / iBGP SOURCE\n"
          f"   ip address {v['lo4']}\n!\n")
    s += "ip routing\n!\n"
    s += f"ip route {v['region4']} Null0 254\n!\n"

    # ---- policy, all values from model/policy.yml
    ml4 = pol["filters"]["max_len4"]
    s += plist4("PL-OURS", [f"permit {pol['ours']['aggregate4']} le {ml4}"])
    s += plist4("PL-OURS-ANY", [f"permit {pol['ours']['aggregate4']} le 32"])
    s += plist4("PL-BOGON", [
        "deny 0.0.0.0/0", "deny 10.0.0.0/8 le 32", "deny 127.0.0.0/8 le 32",
        "deny 169.254.0.0/16 le 32", "deny 172.16.0.0/12 le 32",
        "deny 192.168.0.0/16 le 32", "deny 224.0.0.0/4 le 32",
        f"permit 0.0.0.0/0 ge 8 le {ml4}"])

    for kind in ("transit", "peer"):
        lp, cm = pol["local_pref"][kind], pol["communities"][kind]
        nm = f"RM-{kind.upper()}-IN"
        s += (f"route-map {nm} deny 5\n"
              f"   description never accept our own space from anyone\n"
              f"   match ip address prefix-list PL-OURS-ANY\n!\n"
              f"route-map {nm} permit 10\n"
              f"   match ip address prefix-list PL-BOGON\n"
              f"   set local-preference {lp}\n"
              f"   set community {cm} additive\n!\n")
    s += "route-map RM-OURS-OUT permit 10\n   match ip address prefix-list PL-OURS\n!\n"

    # ---- OSPF / OSPFv3
    s += f"router ospf 1\n   router-id {v['lo4'].split('/')[0]}\n"
    s += f"   network {v['lo4']} area 0.0.0.0\n"
    for ifn in sorted(v["interfaces"], key=lambda x: int(x.replace("Ethernet", ""))):
        i = v["interfaces"][ifn]
        if i["kind"] == "bb":
            s += f"   network {i['net4']} area 0.0.0.0\n"
    s += "   max-lsa 12000\n!\n"

    # ---- BGP
    lo4 = v["lo4"].split("/")[0]
    s += (f"router bgp {asn}\n   router-id {lo4}\n   no bgp default ipv4-unicast\n"
          f"   distance bgp 20 200 200\n   maximum-paths 4 ecmp 4\n"
          f"   bgp log-neighbor-changes\n")
    for p in v["ibgp"]:
        pv = plan["devices"][p["peer"]]
        for addr in (pv["lo4"].split("/")[0],):
            s += (f"   neighbor {addr} remote-as {asn}\n"
                  f"   neighbor {addr} description ibgp_{p['peer']}"
                  f"{'_client' if p['client'] else ''}\n"
                  f"   neighbor {addr} update-source Loopback0\n"
                  f"   neighbor {addr} send-community\n"
                  f"   neighbor {addr} maximum-routes 12000\n")
    for ifn, i in v["interfaces"].items():
        if i["kind"] != "ext":
            continue
        mx = pol["filters"][f"max_prefix_{i['ext_kind']}"]
        for addr in (i["peer_v4"],):
            s += (f"   neighbor {addr} remote-as {i['peer_asn']}\n"
                  f"   neighbor {addr} description {i['ext_kind']}_{i['far']}\n"
                  f"   neighbor {addr} send-community\n"
                  f"   neighbor {addr} maximum-routes {mx}\n")

    s += "   !\n   address-family ipv4\n"
    for p in v["ibgp"]:
        addr = plan["devices"][p["peer"]]["lo4"].split("/")[0]
        s += f"      neighbor {addr} activate\n"
        s += f"      neighbor {addr} next-hop-self\n"
        if p["client"]:
            s += f"      neighbor {addr} route-reflector-client\n"
    for ifn in sorted(v["interfaces"], key=lambda x: int(x.replace("Ethernet", ""))):
        i = v["interfaces"][ifn]
        if i["kind"] != "ext":
            continue
        s += (f"      neighbor {i['peer_v4']} activate\n"
              f"      neighbor {i['peer_v4']} route-map RM-{i['ext_kind'].upper()}-IN in\n"
              f"      neighbor {i['peer_v4']} route-map RM-OURS-OUT out\n")
    s += f"      network {v['region4']}\n"
    return s + "!\nend\n"


def render_peer(plan, peer):
    meta = plan["peers"][peer]
    asn = meta["asn"]
    s = HDR.format(name=peer, role=f"AS {asn} external") + BASE.format(name=peer)
    for e in plan["external"]:
        if e["peer"] != peer:
            continue
        ifn = e["if"][peer]
        s += iface(ifn, f"link{e['id']}_to_{e['device']}", e["b4"], e["mtu"])
    s += "interface Loopback0\n   ip address 10.255.{}.1/32\n!\n".format(asn % 100)
    for n, h4 in enumerate(meta["hosts"], start=1):
        s += (f"interface Loopback{n}\n   description SERVICE_HOST\n"
              f"   ip address {h4}/32\n!\n")
    s += "ip routing\n!\n"
    for p in meta["prefixes4"]:
        s += f"ip route {p} Null0 254\n"
    s += "!\n"
    s += plist4("PL-OWN", [f"permit {p} le 24" for p in meta["prefixes4"]])
    s += "route-map RM-OWN-ONLY permit 10\n   match ip address prefix-list PL-OWN\n!\n"
    s += (f"router bgp {asn}\n   router-id 10.255.{asn % 100}.1\n"
          f"   no bgp default ipv4-unicast\n   maximum-paths 4 ecmp 4\n"
          f"   bgp log-neighbor-changes\n")
    for e in plan["external"]:
        if e["peer"] != peer:
            continue
        for addr in (e["a4"].split("/")[0],):
            s += (f"   neighbor {addr} remote-as {plan['asn']}\n"
                  f"   neighbor {addr} description {e['device']}\n"
                  f"   neighbor {addr} send-community\n"
                  f"   neighbor {addr} maximum-routes 12000\n")
    s += "   !\n   address-family ipv4\n"
    for e in plan["external"]:
        if e["peer"] != peer:
            continue
        s += (f"      neighbor {e['a4'].split('/')[0]} activate\n"
              f"      neighbor {e['a4'].split('/')[0]} route-map RM-OWN-ONLY out\n")
    for p in meta["prefixes4"]:
        s += f"      network {p}\n"
    return s + "!\nend\n"


def render_topology(plan):
    o = ["# bgp-lab16 | GENERATED from model/network.yml by tools/render.py",
         "# The topology is an output of the model, not an input to it.",
         "name: bgp-lab16", "", "mgmt:", "  network: clab-bgp-lab16",
         "  ipv4-subnet: 172.31.116.0/24", "", "topology:", "  kinds:",
         "    arista_ceos:", "      image: ceos:4.36.0.1F", "", "  nodes:"]
    for d in sorted(plan["devices"]):
        v = plan["devices"][d]
        o.append(f"    {d+':':11s} {{kind: arista_ceos, startup-config: configs/active/{d}.cfg}}"
                 f"   # {v['city']}{', route reflector' if v['is_rr'] else ''}")
    for p in sorted(plan["peers"]):
        o.append(f"    {p+':':11s} {{kind: arista_ceos, startup-config: configs/active/{p}.cfg}}"
                 f"   # AS {plan['peers'][p]['asn']}")
    o += ["", "  links:"]
    for l in plan["links"]:
        kind = "intra-region" if l["intra"] else f"{l['rtt']}ms inter-region"
        o += [f"    # link {l['id']}: {kind}, OSPF cost {l['cost']}",
              "    - type: veth", "      endpoints:",
              f"        - node: {l['a']}", f"          interface: {l['if'][l['a']].replace('Ethernet','eth')}",
              f"        - node: {l['b']}", f"          interface: {l['if'][l['b']].replace('Ethernet','eth')}",
              f"      mtu: {l['mtu']}"]
    for e in plan["external"]:
        o += [f"    # link {e['id']}: {e['kind']} handoff to AS {e['asn']}",
              "    - type: veth", "      endpoints:",
              f"        - node: {e['device']}", f"          interface: {e['if'][e['device']].replace('Ethernet','eth')}",
              f"        - node: {e['peer']}", f"          interface: {e['if'][e['peer']].replace('Ethernet','eth')}",
              f"      mtu: {e['mtu']}"]
    return "\n".join(o) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdout", metavar="DEVICE")
    a = ap.parse_args()
    plan = build()
    if a.stdout:
        d = a.stdout
        print(render_device(plan, d) if d in plan["devices"] else render_peer(plan, d))
        return 0
    os.makedirs(OUT, exist_ok=True)
    for d in sorted(plan["devices"]):
        open(os.path.join(OUT, f"{d}.cfg"), "w").write(render_device(plan, d))
        print(f"  {d}.cfg")
    for p in sorted(plan["peers"]):
        open(os.path.join(OUT, f"{p}.cfg"), "w").write(render_peer(plan, p))
        print(f"  {p}.cfg")
    open(os.path.join(ROOT, "bgp-lab16.clab.yml"), "w").write(render_topology(plan))
    print("  bgp-lab16.clab.yml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
