#!/usr/bin/env python3
"""
Render cEOS startup configs for bgp-lab01 from one data model.
Outputs: configs/base/*.cfg (L3 addressing only) and configs/solution/*.cfg (full EVPN-VXLAN).
Stdlib only. Reuse for later labs: change the DATA section, re-run.
"""
from pathlib import Path

# ----------------------------- DATA -----------------------------
VMAC = "00:1c:73:00:00:99"
SPINE_ASN = 65100
ISP_ASN = 65000

SPINES = {"spine1": {"sid": 1, "lo0": "10.0.0.1"},
          "spine2": {"sid": 2, "lo0": "10.0.0.2"}}

VLANS = {
    10: {"name": "RED_WEB",  "vrf": "RED",  "gw": "10.10.10.1/24", "vni": 10010},
    20: {"name": "RED_DB",   "vrf": "RED",  "gw": "10.10.20.1/24", "vni": 10020},
    30: {"name": "BLUE_APP", "vrf": "BLUE", "gw": "10.30.30.1/24", "vni": 10030},
}
VRFS = {"RED": 50001, "BLUE": 50002}

# idx = spine port number and /31 slot. access = {EthN: (vlan, host)}
LEAVES = {
    "leaf1":  {"asn": 65101, "n": 11, "idx": 1, "vrfs": ["RED", "BLUE"],
               "access": {3: (10, "h1"), 4: (30, "h5")}},
    "leaf2":  {"asn": 65102, "n": 12, "idx": 2, "vrfs": ["RED"],
               "access": {3: (10, "h2")}},
    "leaf3":  {"asn": 65103, "n": 13, "idx": 3, "vrfs": ["RED", "BLUE"],
               "access": {3: (20, "h3"), 4: (30, "h4")}},
    "bleaf1": {"asn": 65104, "n": 14, "idx": 4, "vrfs": ["RED", "BLUE"], "access": {},
               "ext": {3: ("RED",  "172.16.1.1/30", "172.16.1.2", "isp1 Ethernet0"),
                       4: ("BLUE", "172.16.2.1/30", "172.16.2.2", "isp1 Ethernet4")}},
}
# ----------------------------------------------------------------


def p2p(sid, idx):
    """spine side .even, leaf side .odd in 10.1.<sid>.0/24"""
    b = (idx - 1) * 2
    return f"10.1.{sid}.{b}", f"10.1.{sid}.{b + 1}"


def header(host, mode):
    return f"""! {host} | bgp-lab01 | {mode} config | generated by tools/gen_configs.py
hostname {host}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode mstp
!
"""


def loopback_policy():
    return """ip prefix-list PL-LOOPBACKS seq 10 permit 10.0.0.0/24 eq 32
ip prefix-list PL-LOOPBACKS seq 20 permit 10.0.1.0/24 eq 32
!
route-map RM-CONN-2-BGP permit 10
   match ip address prefix-list PL-LOOPBACKS
!
"""


def spine(name, d, mode):
    c = header(name, mode)
    for leaf, ld in LEAVES.items():
        s_ip, _ = p2p(d["sid"], ld["idx"])
        c += f"""interface Ethernet{ld['idx']}
   description P2P_{leaf}_Ethernet{d['sid']}
   no switchport
   mtu 9214
   ip address {s_ip}/31
!
"""
    c += f"""interface Loopback0
   description ROUTER_ID_EVPN
   ip address {d['lo0']}/32
!
ip routing
!
"""
    if mode == "base":
        return c + "end\n"
    c += loopback_policy()
    c += f"""router bgp {SPINE_ASN}
   router-id {d['lo0']}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN next-hop-unchanged
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community
   neighbor EVPN maximum-routes 0
"""
    for leaf, ld in LEAVES.items():
        _, l_ip = p2p(d["sid"], ld["idx"])
        c += f"""   neighbor {l_ip} peer group UNDERLAY
   neighbor {l_ip} remote-as {ld['asn']}
   neighbor {l_ip} description {leaf}
"""
    for leaf, ld in LEAVES.items():
        c += f"""   neighbor 10.0.0.{ld['n']} peer group EVPN
   neighbor 10.0.0.{ld['n']} remote-as {ld['asn']}
   neighbor 10.0.0.{ld['n']} description {leaf}-evpn
"""
    c += """   redistribute connected route-map RM-CONN-2-BGP
   !
   address-family evpn
      neighbor EVPN activate
   !
   address-family ipv4
      neighbor UNDERLAY activate
!
end
"""
    return c


def leaf(name, d, mode):
    n, asn = d["n"], d["asn"]
    lo0, vtep = f"10.0.0.{n}", f"10.0.1.{n}"
    vlans = sorted({v for v, _ in d["access"].values()})
    c = header(name, mode)

    if mode == "solution":
        for v in vlans:
            c += f"vlan {v}\n   name {VLANS[v]['name']}\n!\n"
        for vrf in d["vrfs"]:
            c += f"vrf instance {vrf}\n!\n"

    for sname, sd in SPINES.items():
        s_ip, l_ip = p2p(sd["sid"], d["idx"])
        c += f"""interface Ethernet{sd['sid']}
   description P2P_{sname}_Ethernet{d['idx']}
   no switchport
   mtu 9214
   ip address {l_ip}/31
!
"""
    for port, (v, host) in sorted(d["access"].items()):
        c += f"interface Ethernet{port}\n   description HOST_{host}\n"
        if mode == "solution":
            c += f"   switchport access vlan {v}\n   spanning-tree portfast\n   spanning-tree bpduguard enable\n"
        c += "!\n"
    for port, (vrf, ip, _, peer) in sorted(d.get("ext", {}).items()):
        c += f"interface Ethernet{port}\n   description WAN_{peer.replace(' ', '_')}_vrf_{vrf}\n   no switchport\n"
        if mode == "solution":
            c += f"   vrf {vrf}\n"
        c += f"   ip address {ip}\n!\n"

    c += f"""interface Loopback0
   description ROUTER_ID_EVPN
   ip address {lo0}/32
!
interface Loopback1
   description VTEP
   ip address {vtep}/32
!
"""
    if mode == "base":
        return c + "ip routing\n!\nend\n"

    for v in vlans:
        c += f"""interface Vlan{v}
   description {VLANS[v]['name']}
   vrf {VLANS[v]['vrf']}
   ip address virtual {VLANS[v]['gw']}
!
"""
    c += "interface Vxlan1\n   vxlan source-interface Loopback1\n   vxlan udp-port 4789\n"
    for v in vlans:
        c += f"   vxlan vlan {v} vni {VLANS[v]['vni']}\n"
    for vrf in d["vrfs"]:
        c += f"   vxlan vrf {vrf} vni {VRFS[vrf]}\n"
    c += f"!\nip virtual-router mac-address {VMAC}\n!\nip routing\n"
    for vrf in d["vrfs"]:
        c += f"ip routing vrf {vrf}\n"
    c += "!\n" + loopback_policy()

    c += f"""router bgp {asn}
   router-id {lo0}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY remote-as {SPINE_ASN}
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN remote-as {SPINE_ASN}
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community
   neighbor EVPN maximum-routes 0
"""
    for sname, sd in SPINES.items():
        s_ip, _ = p2p(sd["sid"], d["idx"])
        c += f"   neighbor {s_ip} peer group UNDERLAY\n   neighbor {s_ip} description {sname}\n"
    for sname, sd in SPINES.items():
        c += f"   neighbor {sd['lo0']} peer group EVPN\n   neighbor {sd['lo0']} description {sname}-evpn\n"
    c += "   redistribute connected route-map RM-CONN-2-BGP\n   !\n"
    for v in vlans:
        vni = VLANS[v]["vni"]
        c += f"""   vlan {v}
      rd {lo0}:{vni}
      route-target both {vni}:{vni}
      redistribute learned
   !
"""
    c += """   address-family evpn
      neighbor EVPN activate
   !
   address-family ipv4
      neighbor UNDERLAY activate
   !
"""
    ext_by_vrf = {vrf: (ip, peer_ip, peer) for _, (vrf, ip, peer_ip, peer) in d.get("ext", {}).items()}
    for vrf in d["vrfs"]:
        l3 = VRFS[vrf]
        c += f"""   vrf {vrf}
      rd {lo0}:{l3}
      route-target import evpn {l3}:{l3}
      route-target export evpn {l3}:{l3}
      router-id {lo0}
"""
        if vrf in ext_by_vrf:
            _, pip, peer = ext_by_vrf[vrf]
            c += f"""      neighbor {pip} remote-as {ISP_ASN}
      neighbor {pip} description {peer.replace(' ', '_')}
      neighbor {pip} maximum-routes 1000
"""
        c += "      redistribute connected\n"
        if vrf in ext_by_vrf:
            c += f"      !\n      address-family ipv4\n         neighbor {ext_by_vrf[vrf][1]} activate\n"
        c += "   !\n"
    c += "!\nend\n"
    return c


def main():
    root = Path(__file__).resolve().parent.parent
    for mode in ("base", "solution"):
        out = root / "configs" / mode
        out.mkdir(parents=True, exist_ok=True)
        for s, d in SPINES.items():
            (out / f"{s}.cfg").write_text(spine(s, d, mode))
        for l, d in LEAVES.items():
            (out / f"{l}.cfg").write_text(leaf(l, d, mode))
    print("rendered configs/base and configs/solution")


if __name__ == "__main__":
    main()
