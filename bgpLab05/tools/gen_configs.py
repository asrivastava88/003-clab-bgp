#!/usr/bin/env python3
"""
bgp-lab05 config renderer (stdlib only).

The same fabric built two ways, so you can diff them:

  numbered    classic eBGP underlay on /31 point-to-point links (labs 01-03 style)
  unnumbered  no IPv4 on any fabric link. Interface-based eBGP over IPv6
              link-local, carrying IPv4 loopbacks with IPv6 next hops (RFC 8950)

The EVPN overlay stanza is byte-identical in both modes. That is the point:
the overlay does not care how the underlay is built.

  base        unnumbered interfaces enabled, VLAN/SVI/VXLAN/VRF scaffolding,
              NO BGP anywhere. You build underlay and overlay.

Verified EOS requirements for the unnumbered mode (see README sources):
  - 'ipv6 unicast-routing' globally, even though we route no IPv6 prefixes
  - 'ipv6 enable' on each fabric interface, no IPv4 address
  - interface neighbors MUST be bound to a peer group
  - 'next-hop address-family ipv6 originate' under address-family ipv4
  - 'ip routing ipv6 interfaces' for addressless forwarding
  - EOS has no 'remote-as external', so each interface neighbor names its ASN
"""
from pathlib import Path

# ============================ DATA ============================
SPINE_ASN = 65100
VMAC = "00:1c:73:00:00:99"
VRF, L3VNI = "RED", 50001

VLANS = {
    10: {"name": "APP", "gw": "10.10.10.1/24", "vni": 10010},
    20: {"name": "DB",  "gw": "10.10.20.1/24", "vni": 10020},
}

SPINES = {"spine1": {"sid": 1, "n": 1}, "spine2": {"sid": 2, "n": 2}}

# idx = the spine port this leaf lands on, and its /31 slot in numbered mode
LEAVES = {
    "leaf1": {"asn": 65101, "n": 11, "idx": 1, "vlans": [10],     "access": {3: (10, "h1")}},
    "leaf2": {"asn": 65102, "n": 12, "idx": 2, "vlans": [10],     "access": {3: (10, "h2")}},
    "leaf3": {"asn": 65103, "n": 13, "idx": 3, "vlans": [20],     "access": {3: (20, "h3")}},
}

HOSTS = {
    "h1": {"ip": "10.10.10.101/24", "gw": "10.10.10.1", "to": "leaf1 vlan 10"},
    "h2": {"ip": "10.10.10.102/24", "gw": "10.10.10.1", "to": "leaf2 vlan 10"},
    "h3": {"ip": "10.10.20.103/24", "gw": "10.10.20.1", "to": "leaf3 vlan 20"},
}
# ==============================================================


def lo0(n):
    return f"10.0.0.{n}"


def lo1(n):
    return f"10.0.1.{n}"


def p2p(sid, idx):
    b = (idx - 1) * 2
    return f"10.1.{sid}.{b}", f"10.1.{sid}.{b + 1}"


def header(host, mode):
    return f"""! {host} | bgp-lab05 | {mode} | generated by tools/gen_configs.py
hostname {host}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode mstp
!
"""


LOOP_POLICY = """ip prefix-list PL-LOOPBACKS seq 10 permit 10.0.0.0/24 eq 32
ip prefix-list PL-LOOPBACKS seq 20 permit 10.0.1.0/24 eq 32
!
route-map RM-CONN-2-BGP permit 10
   match ip address prefix-list PL-LOOPBACKS
!
"""

# Addressless forwarding needs both of these. Without 'ipv6 unicast-routing'
# EOS never looks for a link-local neighbor, so no session forms at all.
UNNUM_GLOBALS = """! required for interface-based BGP even though no IPv6 prefix is routed
ipv6 unicast-routing
! required so IPv4 traffic can forward out an interface that has no IPv4 address
ip routing ipv6 interfaces
!
"""


def fabric_iface(port, desc, mode, ipv4=None):
    c = f"interface Ethernet{port}\n   description {desc}\n   no switchport\n   mtu 9214\n"
    if mode == "numbered":
        c += f"   ip address {ipv4}\n"
    else:
        c += "   ipv6 enable\n"
    return c + "!\n"


def underlay_bgp(mode, peers, local_is_spine):
    """peers = list of (EthernetN, remote_asn, description).
    In unnumbered mode a leaf collapses to ONE line because both uplinks share
    the spine ASN. A spine needs one line per leaf, because EOS has no
    'remote-as external' and every leaf has its own ASN."""
    c = """   neighbor UNDERLAY peer group
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
"""
    if mode == "numbered":
        for ip, asn, desc in peers:
            c += (f"   neighbor {ip} peer group UNDERLAY\n"
                  f"   neighbor {ip} remote-as {asn}\n"
                  f"   neighbor {ip} description {desc}\n")
    else:
        if local_is_spine:
            for port, asn, desc in peers:
                c += f"   neighbor interface {port} peer-group UNDERLAY remote-as {asn}\n"
        else:
            ports = "-".join([peers[0][0], peers[-1][0].replace("Et", "")]) if len(peers) > 1 else peers[0][0]
            c += f"   neighbor interface {ports} peer-group UNDERLAY remote-as {peers[0][1]}\n"
    return c


def underlay_af(mode):
    c = "   address-family ipv4\n      neighbor UNDERLAY activate\n"
    if mode == "unnumbered":
        c += ("      ! advertise IPv4 NLRI with an IPv6 link-local next hop (RFC 8950)\n"
              "      neighbor UNDERLAY next-hop address-family ipv6 originate\n")
    return c


# The overlay stanza is identical in both modes, on purpose: it peers Loopback0
# to Loopback0 and never touches a fabric interface.
def overlay_peers(remote_asn, next_hop_unchanged):
    c = f"""   neighbor OVERLAY peer group
   neighbor OVERLAY remote-as {remote_asn}
   neighbor OVERLAY update-source Loopback0
   neighbor OVERLAY ebgp-multihop 3
   neighbor OVERLAY send-community extended
   neighbor OVERLAY maximum-routes 0
"""
    if next_hop_unchanged:
        c = c.replace("   neighbor OVERLAY remote-as",
                      "   neighbor OVERLAY next-hop-unchanged\n   neighbor OVERLAY remote-as")
    return c


def spine(name, d, mode):
    c = header(name, mode)
    if mode != "numbered":
        c += UNNUM_GLOBALS
    peers = []
    for leaf, ld in LEAVES.items():
        s_ip, l_ip = p2p(d["sid"], ld["idx"])
        c += fabric_iface(ld["idx"], f"P2P_{leaf}", mode, f"{s_ip}/31")
        # the peer address is the far end of the /31
        peers.append((l_ip if mode == "numbered" else f"Et{ld['idx']}", ld["asn"], leaf))
    c += f"interface Loopback0\n   description ROUTER_ID_AND_OVERLAY_PEERING\n   ip address {lo0(d['n'])}/32\n!\n"
    c += "ip routing\n!\n"
    if mode == "base":
        return c + "end\n"
    c += LOOP_POLICY
    c += f"""router bgp {SPINE_ASN}
   router-id {lo0(d['n'])}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
"""
    c += underlay_bgp(mode, peers, local_is_spine=True)
    # a spine faces three different leaf ASNs, so remote-as goes per neighbor
    c += ("   neighbor OVERLAY peer group\n"
          "   neighbor OVERLAY next-hop-unchanged\n"
          "   neighbor OVERLAY update-source Loopback0\n"
          "   neighbor OVERLAY ebgp-multihop 3\n"
          "   neighbor OVERLAY send-community extended\n"
          "   neighbor OVERLAY maximum-routes 0\n")
    for leaf, ld in LEAVES.items():
        c += (f"   neighbor {lo0(ld['n'])} peer group OVERLAY\n"
              f"   neighbor {lo0(ld['n'])} remote-as {ld['asn']}\n"
              f"   neighbor {lo0(ld['n'])} description {leaf}-evpn\n")
    c += "   redistribute connected route-map RM-CONN-2-BGP\n   !\n"
    c += "   address-family evpn\n      neighbor OVERLAY activate\n   !\n"
    c += underlay_af(mode)
    return c + "!\nend\n"


def leaf(name, d, mode):
    n, asn = d["n"], d["asn"]
    vlans = sorted(d["vlans"])
    c = header(name, mode)
    if mode != "numbered":
        c += UNNUM_GLOBALS
    for v in vlans:
        c += f"vlan {v}\n   name {VLANS[v]['name']}\n!\n"
    c += f"vrf instance {VRF}\n!\n"

    peers = []
    for sname, sd in SPINES.items():
        s_ip, l_ip = p2p(sd["sid"], d["idx"])
        c += fabric_iface(sd["sid"], f"P2P_{sname}", mode, f"{l_ip}/31")
        # the peer address is the far end of the /31
        peers.append((s_ip if mode == "numbered" else f"Et{sd['sid']}", SPINE_ASN, sname))

    for port, (v, h) in sorted(d["access"].items()):
        c += (f"interface Ethernet{port}\n   description HOST_{h}\n"
              f"   switchport access vlan {v}\n   spanning-tree portfast\n"
              f"   spanning-tree bpduguard enable\n!\n")

    c += (f"interface Loopback0\n   description ROUTER_ID_AND_OVERLAY_PEERING\n"
          f"   ip address {lo0(n)}/32\n!\n"
          f"interface Loopback1\n   description VTEP\n   ip address {lo1(n)}/32\n!\n")
    for v in vlans:
        c += (f"interface Vlan{v}\n   description {VLANS[v]['name']}\n   vrf {VRF}\n"
              f"   ip address virtual {VLANS[v]['gw']}\n!\n")
    c += "interface Vxlan1\n   vxlan source-interface Loopback1\n   vxlan udp-port 4789\n"
    for v in vlans:
        c += f"   vxlan vlan {v} vni {VLANS[v]['vni']}\n"
    c += f"   vxlan vrf {VRF} vni {L3VNI}\n!\n"
    c += f"ip virtual-router mac-address {VMAC}\n!\nip routing\nip routing vrf {VRF}\n!\n"
    if mode == "base":
        return c + "end\n"
    c += LOOP_POLICY
    c += f"""router bgp {asn}
   router-id {lo0(n)}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
"""
    c += underlay_bgp(mode, peers, local_is_spine=False)
    c += overlay_peers(SPINE_ASN, next_hop_unchanged=False)
    for sname, sd in SPINES.items():
        c += (f"   neighbor {lo0(sd['n'])} peer group OVERLAY\n"
              f"   neighbor {lo0(sd['n'])} description {sname}-evpn\n")
    c += "   redistribute connected route-map RM-CONN-2-BGP\n   !\n"
    for v in vlans:
        vni = VLANS[v]["vni"]
        c += (f"   vlan {v}\n      rd {lo0(n)}:{vni}\n"
              f"      route-target both {vni}:{vni}\n      redistribute learned\n   !\n")
    c += "   address-family evpn\n      neighbor OVERLAY activate\n   !\n"
    c += underlay_af(mode)
    c += ("   !\n"
          f"   vrf {VRF}\n      rd {lo0(n)}:{L3VNI}\n"
          f"      route-target import evpn {L3VNI}:{L3VNI}\n"
          f"      route-target export evpn {L3VNI}:{L3VNI}\n"
          f"      router-id {lo0(n)}\n"
          f"      maximum-paths 4 ecmp 4\n      redistribute connected\n   !\n")
    return c + "!\nend\n"


def host(name, d):
    c = header(name, "endpoint")
    c += (f"! {name} -> {d['to']}\n!\nspanning-tree mode none\n!\n"
          f"interface Ethernet1\n   description UPLINK\n   no switchport\n"
          f"   ip address {d['ip']}\n!\n"
          f"ip routing\n!\nip route 0.0.0.0/0 {d['gw']}\n!\nend\n")
    return c


def main():
    root = Path(__file__).resolve().parent.parent
    for mode in ("base", "numbered", "unnumbered"):
        out = root / "configs" / mode
        out.mkdir(parents=True, exist_ok=True)
        for s, d in SPINES.items():
            (out / f"{s}.cfg").write_text(spine(s, d, mode))
        for l, d in LEAVES.items():
            (out / f"{l}.cfg").write_text(leaf(l, d, mode))
        for h, d in HOSTS.items():
            (out / f"{h}.cfg").write_text(host(h, d))
    print("rendered configs/{base,numbered,unnumbered}")


if __name__ == "__main__":
    main()
