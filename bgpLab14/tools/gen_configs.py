#!/usr/bin/env python3
"""bgp-lab14 config generator.

AS 65010 is a global content network with four PoPs on a ring. One transit AS
peers with it at all four, which is the only arrangement that makes MED and
hot/cold-potato routing mean anything. A CDN peers at two PoPs and a European
network at one.

Every MED here comes from tools/topology.py, where it is the RTT cost of the
backbone somebody is asking somebody else to carry. Nothing is hand-typed.

Our space is RFC 5737 documentation prefixes plus 198.18.0.0/15 (RFC 2544,
reserved for benchmarking). Peer space is 100.64.0.0/10 (RFC 6598, reserved).
None of it is globally routed, so nothing here teaches you to filter the
wrong thing. Every network name is fictional.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from topology import (POPS, SPANS, dist, our_med, gtt_med, PREFIXES,
                      GTT_CUSTOMERS, CDN_PREFIX, PEEREU_PREFIX, LP, OUR_AS)

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "configs", "solution")
D = dist()
GTT_AS, CDN_AS, PEEREU_AS = 65100, 65300, 65400
MTU_BB, MTU_HANDOFF = 9100, 1500

ANYCAST = "192.0.2.0/24"
AMER, EMEA, APAC, REGIONAL = "198.51.100.0/24", "203.0.113.0/24", "198.18.0.0/24", "198.18.1.0/24"
OUR_ALL = [ANYCAST, AMER, EMEA, APAC, REGIONAL]

# node, interface, ip, description, mtu, ospf cost (None = not in OSPF)
IFACES = {
  "sea": [("Ethernet1","10.100.1.1/30","HANDOFF_gttw_Seattle",MTU_HANDOFF,None),
          ("Ethernet2","10.254.0.0/31","BACKBONE_ash_65ms",MTU_BB,65),
          ("Ethernet3","10.254.0.7/31","BACKBONE_sin_175ms",MTU_BB,175)],
  "ash": [("Ethernet1","10.100.3.1/30","HANDOFF_gtte_Ashburn",MTU_HANDOFF,None),
          ("Ethernet2","10.254.0.1/31","BACKBONE_sea_65ms",MTU_BB,65),
          ("Ethernet3","10.254.0.2/31","BACKBONE_lhr_75ms",MTU_BB,75)],
  "lhr": [("Ethernet1","10.100.4.1/30","HANDOFF_gtte_London",MTU_HANDOFF,None),
          ("Ethernet2","10.254.0.3/31","BACKBONE_ash_75ms",MTU_BB,75),
          ("Ethernet3","10.254.0.4/31","BACKBONE_sin_160ms",MTU_BB,160),
          ("Ethernet4","10.150.1.1/30","PNI_cdn_London",MTU_BB,None),
          ("Ethernet5","10.160.1.1/30","PEER_peereu_London",MTU_HANDOFF,None)],
  "sin": [("Ethernet1","10.100.2.1/30","HANDOFF_gttw_Singapore",MTU_HANDOFF,None),
          ("Ethernet2","10.254.0.5/31","BACKBONE_lhr_160ms",MTU_BB,160),
          ("Ethernet3","10.254.0.6/31","BACKBONE_sea_175ms",MTU_BB,175),
          ("Ethernet4","10.150.2.1/30","PNI_cdn_Singapore",MTU_BB,None)],
}
LO = {"sea":"10.255.0.1","ash":"10.255.0.2","lhr":"10.255.0.3","sin":"10.255.0.4"}
GTT_PEER = {"sea":"10.100.1.2","ash":"10.100.3.2","lhr":"10.100.4.2","sin":"10.100.2.2"}
# which of our prefixes each PoP originates
ORIGINATE = {"sea":[ANYCAST,AMER], "ash":[ANYCAST], "lhr":[ANYCAST,EMEA],
             "sin":[ANYCAST,APAC,REGIONAL]}
HOSTS = {"sea":[(1,"192.0.2.1"),(2,"198.51.100.1")], "ash":[(1,"192.0.2.1")],
         "lhr":[(1,"192.0.2.1"),(2,"203.0.113.1")],
         "sin":[(1,"192.0.2.1"),(2,"198.18.0.1"),(3,"198.18.1.1")]}

BASE = """hostname {name}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode none
!
"""

def iface(n, ip, desc, mtu, cost):
    s = f"interface {n}\n   description {desc}\n   no switchport\n   mtu {mtu}\n   ip address {ip}\n"
    if cost is not None:
        s += f"   ip ospf cost {cost}\n"
    return s + "!\n"

def lo(n, ip, desc=""):
    d = f"   description {desc}\n" if desc else ""
    return f"interface Loopback{n}\n{d}   ip address {ip}/32\n!\n"

def plist(name, entries):
    return "".join(f"ip prefix-list {name} seq {i*10} {e}\n"
                   for i, e in enumerate(entries, 1)) + "!\n"

BOGON = ["deny 0.0.0.0/0","deny 0.0.0.0/8 le 32","deny 10.0.0.0/8 le 32",
         "deny 127.0.0.0/8 le 32","deny 169.254.0.0/16 le 32","deny 172.16.0.0/12 le 32",
         "deny 192.168.0.0/16 le 32","deny 224.0.0.0/4 le 32","deny 240.0.0.0/4 le 32",
         "permit 0.0.0.0/0 ge 8 le 24"]

def our_pop(pop):
    s = f"! {pop} | bgp-lab14 | AS {OUR_AS} PoP, {pop} | generated by tools/gen_configs.py\n"
    s += BASE.format(name=pop)
    for a in IFACES[pop]:
        s += iface(*a)
    s += lo(0, LO[pop], "ROUTER_ID / iBGP SOURCE")
    for n, ip in HOSTS[pop]:
        s += lo(n, ip, "ANYCAST_SERVICE" if ip == "192.0.2.1" else "REGIONAL_SERVICE")
    s += "ip routing\n!\n"
    for p in ORIGINATE[pop]:
        s += f"ip route {p} Null0 254\n"
    s += "!\n"
    # ---- prefix lists
    s += plist("PL-ANYCAST", [f"permit {ANYCAST}"])
    s += plist("PL-AMER", [f"permit {AMER}"])
    s += plist("PL-EMEA", [f"permit {EMEA}"])
    s += plist("PL-APAC", [f"permit {APAC}"])
    s += plist("PL-REGIONAL", [f"permit {REGIONAL}"])
    s += plist("PL-OUR-ALL", [f"permit {p} le 32" for p in OUR_ALL])
    s += plist("PL-CDN", [f"permit {CDN_PREFIX} le 24"])
    s += plist("PL-PEEREU", [f"permit {PEEREU_PREFIX} le 24"])
    s += plist("PL-BOGON", BOGON)
    # ---- outbound: MED is how far we will carry it
    def outmap(name, regional):
        t = ""
        for seq, (pl, home) in enumerate(
                [("PL-ANYCAST", None), ("PL-AMER", "sea"),
                 ("PL-EMEA", "lhr"), ("PL-APAC", "sin")], start=1):
            med = 0 if home is None else D[pop][home]
            t += (f"route-map {name} permit {seq*10}\n"
                  f"   match ip address prefix-list {pl}\n"
                  f"   set metric {med}\n!\n")
        if regional and REGIONAL in ORIGINATE[pop]:
            t += (f"route-map {name} permit 50\n"
                  f"   description regional service, must not leave the transit AS\n"
                  f"   match ip address prefix-list PL-REGIONAL\n"
                  f"   set metric 0\n"
                  f"   set community no-export additive\n!\n")
        return t
    s += outmap("RM-GTT-OUT", regional=True)
    s += outmap("RM-EXT-OUT", regional=False)
    # ---- inbound. We deliberately keep the peer's MED rather than zeroing it.
    def inmap(name, allow, lp, note):
        return (f"route-map {name} deny 5\n"
                f"   description never accept our own space from anyone\n"
                f"   match ip address prefix-list PL-OUR-ALL\n!\n"
                f"route-map {name} permit 10\n"
                f"   description {note}\n"
                f"   match ip address prefix-list {allow}\n"
                f"   set local-preference {lp}\n!\n")
    s += inmap("RM-GTT-IN", "PL-BOGON", LP["transit"],
               "MED preserved on purpose: that is the cold-potato decision")
    if pop in ("lhr", "sin"):
        s += inmap("RM-PNI-IN", "PL-CDN", LP["pni"], "CDN private interconnect")
    if pop == "lhr":
        s += inmap("RM-PEER-IN", "PL-PEEREU", LP["peer"], "European peer, London only")
    # ---- OSPF
    s += f"router ospf 1\n   router-id {LO[pop]}\n   network {LO[pop]}/32 area 0.0.0.0\n"
    for n, ip, desc, mtu, cost in IFACES[pop]:
        if cost is not None:
            net = ip.rsplit("/", 1)[0]
            o = net.split(".")
            base = f"{o[0]}.{o[1]}.{o[2]}.{int(o[3]) & ~1}/31"
            s += f"   network {base} area 0.0.0.0\n"
    s += "   max-lsa 12000\n!\n"
    # ---- BGP
    s += f"router bgp {OUR_AS}\n   router-id {LO[pop]}\n   no bgp default ipv4-unicast\n"
    s += "   distance bgp 20 200 200\n   maximum-paths 2 ecmp 2\n   bgp log-neighbor-changes\n"
    s += "   neighbor IBGP peer group\n"
    s += f"   neighbor IBGP remote-as {OUR_AS}\n"
    s += "   neighbor IBGP update-source Loopback0\n   neighbor IBGP next-hop-self\n"
    s += "   neighbor IBGP send-community\n   neighbor IBGP maximum-routes 12000\n"
    for q in POPS:
        if q != pop:
            s += f"   neighbor {LO[q]} peer group IBGP\n   neighbor {LO[q]} description {q}\n"
    grp = [("GTT", GTT_AS, GTT_PEER[pop], "RM-GTT-IN", "RM-GTT-OUT", 12000, "global transit")]
    if pop == "lhr":
        grp += [("PNI", CDN_AS, "10.150.1.2", "RM-PNI-IN", "RM-EXT-OUT", 500, "cdn PNI London"),
                ("PEER", PEEREU_AS, "10.160.1.2", "RM-PEER-IN", "RM-EXT-OUT", 500, "european peer")]
    if pop == "sin":
        grp += [("PNI", CDN_AS, "10.150.2.2", "RM-PNI-IN", "RM-EXT-OUT", 500, "cdn PNI Singapore")]
    for name, asn, ip, rin, rout, maxr, desc in grp:
        s += f"   neighbor {name} peer group\n   neighbor {name} remote-as {asn}\n"
        s += f"   neighbor {name} send-community\n"
        s += f"   neighbor {name} route-map {rin} in\n   neighbor {name} route-map {rout} out\n"
        s += f"   neighbor {name} maximum-routes {maxr}\n"
        s += f"   neighbor {ip} peer group {name}\n   neighbor {ip} description {desc}\n"
    for p in ORIGINATE[pop]:
        s += f"   network {p}\n"
    s += "   !\n   address-family ipv4\n      neighbor IBGP activate\n"
    for name, *_ in grp:
        s += f"      neighbor {name} activate\n"
    return s + "!\nend\n"


def gtt(node):
    """The transit. Per-session MED route-maps are the whole point of it."""
    west = node == "gttw"
    rid = "10.255.1.1" if west else "10.255.1.2"
    peer_rid = "10.255.1.2" if west else "10.255.1.1"
    s = f"! {node} | bgp-lab14 | AS {GTT_AS} global transit, {'west' if west else 'east'} | generated\n"
    s += BASE.format(name=node)
    if west:
        ifs = [("Ethernet1","10.100.1.2/30","HANDOFF_sea",MTU_HANDOFF,None),
               ("Ethernet2","10.100.2.2/30","HANDOFF_sin",MTU_HANDOFF,None),
               ("Ethernet3","10.110.0.1/30","INTERNAL_gtte_70ms",MTU_BB,70)]
        sessions = [("10.100.1.1","sea"), ("10.100.2.1","sin")]
        hosts = [(1,"100.150.0.1"),(2,"100.151.0.1"),(3,"100.200.0.1")]
    else:
        ifs = [("Ethernet1","10.100.3.2/30","HANDOFF_ash",MTU_HANDOFF,None),
               ("Ethernet2","10.100.4.2/30","HANDOFF_lhr",MTU_HANDOFF,None),
               ("Ethernet3","10.110.0.2/30","INTERNAL_gttw_70ms",MTU_BB,70),
               ("Ethernet4","10.160.2.1/30","CUSTOMER_peereu",MTU_HANDOFF,None)]
        sessions = [("10.100.3.1","ash"), ("10.100.4.1","lhr")]
        # 100.200.0.1 lives on both transit routers: the transit-only prefix is
        # hot-potatoed, so each of our PoPs reaches a different one of them
        hosts = [(1,"100.152.0.1"),(2,"100.153.0.1"),(3,"100.200.0.1")]
    for a in ifs:
        s += iface(*a)
    s += lo(0, rid, "ROUTER_ID")
    for n, ip in hosts:
        s += lo(n, ip, "CUSTOMER_HOST")
    s += "ip routing\n!\n"
    for p in GTT_CUSTOMERS:
        s += f"ip route {p} Null0 254\n"
    s += "!\n"
    for p in GTT_CUSTOMERS:
        tag = p.split(".")[1] + "-" + p.split(".")[2]
        s += plist(f"PL-C-{tag}", [f"permit {p} le 24"])
    s += plist("PL-PEEREU", [f"permit {PEEREU_PREFIX} le 24"])
    s += plist("PL-OWN-ALL", [f"permit {p} le 24" for p in list(GTT_CUSTOMERS) + [PEEREU_PREFIX]])
    # one outbound map per handoff city, MED = our internal distance from there
    for ip, pop in sessions:
        name = f"RM-OUT-{pop.upper()}"
        seq = 10
        for p, (home, label) in GTT_CUSTOMERS.items():
            tag = p.split(".")[1] + "-" + p.split(".")[2]
            s += (f"route-map {name} permit {seq}\n"
                  f"   description {label}: {gtt_med(pop, p, D)}ms of our backbone from {pop}\n"
                  f"   match ip address prefix-list PL-C-{tag}\n"
                  f"   set metric {gtt_med(pop, p, D)}\n!\n")
            seq += 10
        s += (f"route-map {name} permit {seq}\n"
              f"   description european customer, homed at London\n"
              f"   match ip address prefix-list PL-PEEREU\n"
              f"   set metric {D[pop]['lhr']}\n!\n")
    s += ("route-map RM-OWN-ONLY permit 10\n   match ip address prefix-list PL-OWN-ALL\n!\n")
    s += f"router ospf 1\n   router-id {rid}\n   network {rid}/32 area 0.0.0.0\n"
    s += "   network 10.110.0.0/30 area 0.0.0.0\n   max-lsa 12000\n!\n"
    s += f"router bgp {GTT_AS}\n   router-id {rid}\n   no bgp default ipv4-unicast\n"
    s += "   maximum-paths 2 ecmp 2\n   bgp log-neighbor-changes\n"
    s += f"   neighbor {peer_rid} remote-as {GTT_AS}\n"
    s += f"   neighbor {peer_rid} update-source Loopback0\n"
    s += f"   neighbor {peer_rid} next-hop-self\n   neighbor {peer_rid} send-community\n"
    s += f"   neighbor {peer_rid} maximum-routes 12000\n"
    for ip, pop in sessions:
        s += f"   neighbor {ip} remote-as {OUR_AS}\n   neighbor {ip} description {pop}\n"
        s += f"   neighbor {ip} send-community\n"
        s += f"   neighbor {ip} route-map RM-OUT-{pop.upper()} out\n"
        s += f"   neighbor {ip} maximum-routes 12000\n"
    if not west:
        s += (f"   neighbor 10.160.2.2 remote-as {PEEREU_AS}\n"
              f"   neighbor 10.160.2.2 description peereu_customer\n"
              f"   neighbor 10.160.2.2 send-community\n"
              f"   neighbor 10.160.2.2 maximum-routes 500\n")
    for p in GTT_CUSTOMERS:
        s += f"   network {p}\n"
    s += "   !\n   address-family ipv4\n"
    s += f"      neighbor {peer_rid} activate\n"
    for ip, _ in sessions:
        s += f"      neighbor {ip} activate\n"
    if not west:
        s += "      neighbor 10.160.2.2 activate\n"
    return s + "!\nend\n"


def stub(name, role, asn, rid, ifs, prefixes, hosts, peers):
    s = f"! {name} | bgp-lab14 | {role} | generated by tools/gen_configs.py\n"
    s += BASE.format(name=name)
    for a in ifs:
        s += iface(*a)
    s += lo(0, rid, "ROUTER_ID")
    for n, ip in hosts:
        s += lo(n, ip, "SERVICE_HOST")
    s += "ip routing\n!\n"
    for p in prefixes:
        s += f"ip route {p} Null0 254\n"
    s += "!\n"
    s += plist("PL-OWN", [f"permit {p} le 24" for p in prefixes])
    s += ("route-map RM-OWN-ONLY permit 10\n   match ip address prefix-list PL-OWN\n"
          "   set metric 0\n!\n")
    s += f"router bgp {asn}\n   router-id {rid}\n   no bgp default ipv4-unicast\n"
    s += "   maximum-paths 2 ecmp 2\n   bgp log-neighbor-changes\n"
    for ip, pasn, desc in peers:
        s += f"   neighbor {ip} remote-as {pasn}\n   neighbor {ip} description {desc}\n"
        s += f"   neighbor {ip} send-community\n"
        s += f"   neighbor {ip} route-map RM-OWN-ONLY out\n"
        s += f"   neighbor {ip} maximum-routes 12000\n"
    for p in prefixes:
        s += f"   network {p}\n"
    s += "   !\n   address-family ipv4\n"
    for ip, *_ in peers:
        s += f"      neighbor {ip} activate\n"
    return s + "!\nend\n"


def build():
    c = {p: our_pop(p) for p in POPS}
    c["gttw"] = gtt("gttw")
    c["gtte"] = gtt("gtte")
    c["cdn"] = stub("cdn", f"AS {CDN_AS} SOUNDVIEW CDN, PNI at London and Singapore",
                    CDN_AS, "10.255.3.1",
                    [("Ethernet1","10.150.1.2/30","PNI_lhr",MTU_BB,None),
                     ("Ethernet2","10.150.2.2/30","PNI_sin",MTU_BB,None)],
                    [CDN_PREFIX], [(1,"100.120.0.1")],
                    [("10.150.1.1",OUR_AS,"lhr"),("10.150.2.1",OUR_AS,"sin")])
    c["peereu"] = stub("peereu", f"AS {PEEREU_AS} MERIDIAN EU, peers at London, transit customer of {GTT_AS}",
                       PEEREU_AS, "10.255.4.1",
                       [("Ethernet1","10.160.1.2/30","PEER_lhr",MTU_HANDOFF,None),
                        ("Ethernet2","10.160.2.2/30","TRANSIT_gtte",MTU_HANDOFF,None)],
                       [PEEREU_PREFIX], [(1,"100.140.0.1")],
                       [("10.160.1.1",OUR_AS,"lhr_peering"),("10.160.2.1",GTT_AS,"gtte_transit")])
    return c

if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for name, text in build().items():
        open(os.path.join(OUT, f"{name}.cfg"), "w").write(text)
        print(f"  {name}.cfg  {len(text.splitlines())} lines")
