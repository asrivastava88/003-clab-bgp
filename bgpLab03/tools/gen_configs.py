#!/usr/bin/env python3
"""
bgp-lab03 config renderer (stdlib only).

Two redundancy designs side by side on one fabric:
  leaf1 + leaf2  EVPN multihoming (ESI-LAG), unique ASNs, unique VTEPs, no peer link
  leaf3 + leaf4  MLAG,                        shared ASN, shared VTEP IP, peer link

Modes:
  base      fabric + EVPN + VRF + single-homed ports only. Port-Channels exist,
            but no ESI, no MLAG, no LACP system-id. You build the redundancy.
  solution  full reference for both designs.
"""
from pathlib import Path

# ============================ DATA ============================
VMAC = "00:1c:73:00:00:99"
SPINE_ASN = 65100
SPINES = {"spine1": {"sid": 1, "lo0": "10.0.0.1"},
          "spine2": {"sid": 2, "lo0": "10.0.0.2"}}

VLANS = {
    10: {"name": "APP",  "gw": "10.10.10.1/24", "vni": 10010},
    20: {"name": "DB",   "gw": "10.10.20.1/24", "vni": 10020},
}
VRF, L3VNI = "RED", 50001

# ESI-LAG (leaf1/leaf2) -> hm1
ESI       = "0011:1111:1111:1111:1111"
ES_RT     = "00:11:11:11:11:11"          # ES-import route-target, derived from the ESI
LACP_SYS  = "0011.1111.1111"             # both leaves present this to the host
ES_PO     = 1

# MLAG (leaf3/leaf4)
MLAG_DOMAIN = "MLAG34"
MLAG_PEERVL = 4094
MLAG_PO     = 2
PEER_PO     = 1000
PEER_IP     = {3: "10.255.34.0", 4: "10.255.34.1"}   # /31 over the peer link
SHARED_VTEP = "10.0.1.34"

LEAVES = {
    # idx = spine port number; n = loopback0 host octet
    "leaf1": {"asn": 65101, "n": 11, "idx": 1, "role": "esi", "vtep": "10.0.1.11",
              "vlans": [10, 20], "esi_port": 3, "access": {4: (10, "hs1")}},
    "leaf2": {"asn": 65102, "n": 12, "idx": 2, "role": "esi", "vtep": "10.0.1.12",
              "vlans": [10, 20], "esi_port": 3, "access": {}},
    "leaf3": {"asn": 65134, "n": 13, "idx": 3, "role": "mlag", "mid": 3, "vtep": SHARED_VTEP,
              "vlans": [10, 20], "mlag_port": 3, "peer_port": 5, "access": {4: (20, "hs2")}},
    "leaf4": {"asn": 65134, "n": 14, "idx": 4, "role": "mlag", "mid": 4, "vtep": SHARED_VTEP,
              "vlans": [10, 20], "mlag_port": 3, "peer_port": 5, "access": {}},
}
# ==============================================================


def p2p(sid, idx):
    b = (idx - 1) * 2
    return f"10.1.{sid}.{b}", f"10.1.{sid}.{b + 1}"


def header(host, mode):
    return f"""! {host} | bgp-lab03 | {mode} | generated by tools/gen_configs.py
hostname {host}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
"""


LOOP_POLICY = """ip prefix-list PL-LOOPBACKS seq 10 permit 10.0.0.0/24 eq 32
ip prefix-list PL-LOOPBACKS seq 20 permit 10.0.1.0/24 eq 32
!
route-map RM-CONN-2-BGP permit 10
   match ip address prefix-list PL-LOOPBACKS
!
"""


def spine(name, d, mode):
    c = header(name, mode) + "spanning-tree mode mstp\n!\n"
    for leaf, ld in LEAVES.items():
        s_ip, _ = p2p(d["sid"], ld["idx"])
        c += (f"interface Ethernet{ld['idx']}\n   description P2P_{leaf}\n"
              f"   no switchport\n   mtu 9214\n   ip address {s_ip}/31\n!\n")
    c += f"interface Loopback0\n   ip address {d['lo0']}/32\n!\nip routing\n!\n" + LOOP_POLICY
    c += f"""router bgp {SPINE_ASN}
   router-id {d['lo0']}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN next-hop-unchanged
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community extended
   neighbor EVPN maximum-routes 0
"""
    for leaf, ld in LEAVES.items():
        _, l_ip = p2p(d["sid"], ld["idx"])
        c += (f"   neighbor {l_ip} peer group UNDERLAY\n"
              f"   neighbor {l_ip} remote-as {ld['asn']}\n"
              f"   neighbor {l_ip} description {leaf}\n")
    for leaf, ld in LEAVES.items():
        ip = f"10.0.0.{ld['n']}"
        c += (f"   neighbor {ip} peer group EVPN\n"
              f"   neighbor {ip} remote-as {ld['asn']}\n"
              f"   neighbor {ip} description {leaf}-evpn\n")
    c += """   redistribute connected route-map RM-CONN-2-BGP
   !
   address-family evpn
      neighbor EVPN activate
   !
   address-family ipv4
      neighbor UNDERLAY activate
!
end
"""
    return c


def leaf(name, d, mode):
    n, asn, role = d["n"], d["asn"], d["role"]
    lo0 = f"10.0.0.{n}"
    full = mode == "solution"
    c = header(name, mode)

    # --- spanning tree -------------------------------------------------
    # EVPN MH and MLAG both rely on the leaf pair looking like one bridge to
    # the host. STP stays on for loop safety on orphan ports.
    c += "spanning-tree mode mstp\n"
    if role == "mlag" and full:
        c += f"no spanning-tree vlan-id {MLAG_PEERVL}\n"
    c += "!\n"

    for v in d["vlans"]:
        c += f"vlan {v}\n   name {VLANS[v]['name']}\n!\n"
    if role == "mlag" and full:
        c += f"vlan {MLAG_PEERVL}\n   name MLAG_PEER\n   trunk group MLAGPEER\n!\n"
    c += f"vrf instance {VRF}\n!\n"

    # --- fabric uplinks ------------------------------------------------
    for sname, sd in SPINES.items():
        _, l_ip = p2p(sd["sid"], d["idx"])
        c += (f"interface Ethernet{sd['sid']}\n   description P2P_{sname}\n"
              f"   no switchport\n   mtu 9214\n   ip address {l_ip}/31\n!\n")

    # --- ESI-LAG member + Port-Channel ---------------------------------
    if role == "esi":
        c += (f"interface Ethernet{d['esi_port']}\n   description HOST_hm1_ESI_LAG\n"
              f"   channel-group {ES_PO} mode active\n!\n")
        c += (f"interface Port-Channel{ES_PO}\n   description HOST_hm1_ESI_LAG\n"
              f"   switchport access vlan 10\n")
        if full:
            c += (f"   !\n"
                  f"   evpn ethernet-segment\n"
                  f"      identifier {ESI}\n"
                  f"      route-target import {ES_RT}\n"
                  f"   !\n"
                  f"   lacp system-id {LACP_SYS}\n")
        c += "!\n"

    # --- MLAG member, Port-Channel, peer link --------------------------
    if role == "mlag":
        c += (f"interface Ethernet{d['mlag_port']}\n   description HOST_hm2_MLAG\n"
              f"   channel-group {MLAG_PO} mode active\n!\n")
        c += (f"interface Port-Channel{MLAG_PO}\n   description HOST_hm2_MLAG\n"
              f"   switchport access vlan 10\n")
        if full:
            c += f"   mlag {MLAG_PO}\n"
        c += "!\n"
        c += (f"interface Ethernet{d['peer_port']}\n   description MLAG_PEER_LINK\n"
              f"   channel-group {PEER_PO} mode active\n!\n")
        c += f"interface Port-Channel{PEER_PO}\n   description MLAG_PEER_LINK\n   switchport mode trunk\n"
        if full:
            c += "   switchport trunk group MLAGPEER\n"
        c += "!\n"
        if full:
            c += (f"interface Vlan{MLAG_PEERVL}\n   description MLAG_PEER\n"
                  f"   no autostate\n   ip address {PEER_IP[d['mid']]}/31\n!\n")

    # --- orphan / single-homed access ports ----------------------------
    for port, (v, host) in sorted(d["access"].items()):
        c += (f"interface Ethernet{port}\n   description HOST_{host}_single_homed\n"
              f"   switchport access vlan {v}\n   spanning-tree portfast\n"
              f"   spanning-tree bpduguard enable\n!\n")

    # --- loopbacks -----------------------------------------------------
    c += f"interface Loopback0\n   description ROUTER_ID_EVPN\n   ip address {lo0}/32\n!\n"
    c += "interface Loopback1\n   description VTEP"
    if role == "mlag":
        c += " (shared across the MLAG pair)"
    c += f"\n   ip address {d['vtep']}/32\n!\n"

    # --- SVIs, VXLAN ---------------------------------------------------
    for v in d["vlans"]:
        c += (f"interface Vlan{v}\n   description {VLANS[v]['name']}\n   vrf {VRF}\n"
              f"   ip address virtual {VLANS[v]['gw']}\n!\n")
    c += "interface Vxlan1\n   vxlan source-interface Loopback1\n   vxlan udp-port 4789\n"
    for v in d["vlans"]:
        c += f"   vxlan vlan {v} vni {VLANS[v]['vni']}\n"
    c += f"   vxlan vrf {VRF} vni {L3VNI}\n!\n"
    c += f"ip virtual-router mac-address {VMAC}\n!\nip routing\nip routing vrf {VRF}\n!\n"

    # --- MLAG domain ---------------------------------------------------
    if role == "mlag" and full:
        peer_ip = PEER_IP[4 if d["mid"] == 3 else 3]
        c += f"""mlag configuration
   domain-id {MLAG_DOMAIN}
   local-interface Vlan{MLAG_PEERVL}
   peer-address {peer_ip}
   peer-link Port-Channel{PEER_PO}
   reload-delay mlag 330
   reload-delay non-mlag 300
!
"""
    c += LOOP_POLICY

    # --- BGP -----------------------------------------------------------
    c += f"""router bgp {asn}
   router-id {lo0}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY remote-as {SPINE_ASN}
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN remote-as {SPINE_ASN}
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community extended
   neighbor EVPN maximum-routes 0
"""
    for sname, sd in SPINES.items():
        s_ip, _ = p2p(sd["sid"], d["idx"])
        c += f"   neighbor {s_ip} peer group UNDERLAY\n   neighbor {s_ip} description {sname}\n"
    for sname, sd in SPINES.items():
        c += f"   neighbor {sd['lo0']} peer group EVPN\n   neighbor {sd['lo0']} description {sname}-evpn\n"
    # MLAG peers share an ASN, so the fabric drops each other's routes as an AS
    # loop. The peer-link session carries the underlay between them.
    if role == "mlag" and full:
        peer_ip = PEER_IP[4 if d["mid"] == 3 else 3]
        c += (f"   neighbor {peer_ip} remote-as {asn}\n"
              f"   neighbor {peer_ip} description mlag-peer\n"
              f"   neighbor {peer_ip} next-hop-self\n"
              f"   neighbor {peer_ip} maximum-routes 12000\n")
    c += "   redistribute connected route-map RM-CONN-2-BGP\n   !\n"
    for v in d["vlans"]:
        vni = VLANS[v]["vni"]
        c += (f"   vlan {v}\n      rd {lo0}:{vni}\n"
              f"      route-target both {vni}:{vni}\n      redistribute learned\n   !\n")
    c += "   address-family evpn\n      neighbor EVPN activate\n   !\n"
    c += "   address-family ipv4\n      neighbor UNDERLAY activate\n"
    if role == "mlag" and full:
        peer_ip = PEER_IP[4 if d["mid"] == 3 else 3]
        c += f"      neighbor {peer_ip} activate\n"
    c += "   !\n"
    c += (f"   vrf {VRF}\n      rd {lo0}:{L3VNI}\n"
          f"      route-target import evpn {L3VNI}:{L3VNI}\n"
          f"      route-target export evpn {L3VNI}:{L3VNI}\n"
          f"      router-id {lo0}\n      redistribute connected\n   !\n")
    return c + "!\nend\n"


def main():
    root = Path(__file__).resolve().parent.parent
    for mode in ("base", "solution"):
        out = root / "configs" / mode
        out.mkdir(parents=True, exist_ok=True)
        for s, d in SPINES.items():
            (out / f"{s}.cfg").write_text(spine(s, d, mode))
        for l, d in LEAVES.items():
            (out / f"{l}.cfg").write_text(leaf(l, d, mode))
    print("rendered configs/base and configs/solution")


if __name__ == "__main__":
    main()
