#!/usr/bin/env python3
"""
bgp-lab02 config renderer (stdlib only).
Modes:
  base      fabric + EVPN + VRFs complete, border subinterfaces addressed, NO ISP BGP (you build the edge)
  solution  edge baseline: per-VRF eBGP to both ISPs, inbound/outbound filtering, no TE
  te        production reference: egress/ingress TE, MED, communities, RTBH (armed), BFD
ISP routers (ispA, ispB) are provider-managed and identical in every mode.
"""
from pathlib import Path

# ============================ DATA ============================
VMAC, SPINE_ASN, BORDER_ASN = "00:1c:73:00:00:99", 65100, 65104
SPINES = {"spine1": {"sid": 1, "lo0": "10.0.0.1"}, "spine2": {"sid": 2, "lo0": "10.0.0.2"}}
VLANS = {
    10: {"name": "RED_WEB",  "vrf": "RED",  "gw": "10.10.10.1/24", "vni": 10010},
    20: {"name": "RED_DB",   "vrf": "RED",  "gw": "10.10.20.1/24", "vni": 10020},
    30: {"name": "BLUE_APP", "vrf": "BLUE", "gw": "10.30.30.1/24", "vni": 10030},
}
VRFS = {"RED":  {"l3vni": 50001, "dot1q": 101, "off": 0, "agg": "10.10.0.0/16"},
        "BLUE": {"l3vni": 50002, "dot1q": 102, "off": 4, "agg": "10.30.0.0/16"}}
LEAVES = {
    "leaf1":  {"asn": 65101, "n": 11, "idx": 1, "access": {3: (10, "h1"), 4: (30, "h3")}},
    "leaf2":  {"asn": 65102, "n": 12, "idx": 2, "access": {3: (20, "h2"), 4: (30, "h4")}},
    "bleaf1": {"asn": BORDER_ASN, "n": 14, "idx": 3, "bid": 1, "access": {}},
    "bleaf2": {"asn": BORDER_ASN, "n": 15, "idx": 4, "bid": 2, "access": {}},
}
# iid = digit in 172.16.<iid><bid>.x ; border port = Ethernet<bport>
ISPS = {"ispA": {"asn": 65010, "iid": 1, "bport": 3, "lo0": "10.255.1.1", "cust_net": "192.0.2.0/24",
                 "cust_ip": "192.0.2.1", "bh": "192.0.2.254", "inet": ("100.64.1.1/30", "100.64.1.2")},
        "ispB": {"asn": 65020, "iid": 2, "bport": 4, "lo0": "10.255.2.1", "cust_net": "198.51.100.0/24",
                 "cust_ip": "198.51.100.1", "bh": "198.51.100.254", "inet": ("100.64.2.1/30", "100.64.2.2")}}
INET_ASN = 65000
INTERNET = ["0.0.0.0/0", "192.0.2.0/24", "198.51.100.0/24", "203.0.113.0/24"]
# TE intent
PRIMARY = {"RED": "ispA", "BLUE": "ispB"}              # egress + ingress preference per VRF
MED = {"RED": {1: 50, 2: 100}, "BLUE": {1: 100, 2: 50}}  # per VRF per border id (lower wins)
COMM_PRI, COMM_BKP = f"{BORDER_ASN}:200", f"{BORDER_ASN}:50"
RTBH_PLACEHOLDER = "10.10.255.255/32"
BFD = "bfd interval 300 min-rx 300 multiplier 3"
# ==============================================================


def p2p(sid, idx):
    b = (idx - 1) * 2
    return f"10.1.{sid}.{b}", f"10.1.{sid}.{b + 1}"


def wan(isp, bid, vrf):
    """returns (border_ip, isp_ip) on the per-VRF /30"""
    o = VRFS[vrf]["off"]
    pre = f"172.16.{ISPS[isp]['iid']}{bid}"
    return f"{pre}.{o + 1}", f"{pre}.{o + 2}"


def header(host, mode):
    return f"""! {host} | bgp-lab02 | {mode} | generated by tools/gen_configs.py
hostname {host}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode mstp
!
"""


LOOP_POLICY = """ip prefix-list PL-LOOPBACKS seq 10 permit 10.0.0.0/24 eq 32
ip prefix-list PL-LOOPBACKS seq 20 permit 10.0.1.0/24 eq 32
!
route-map RM-CONN-2-BGP permit 10
   match ip address prefix-list PL-LOOPBACKS
!
"""

COMMON_BGP = """   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
"""


def spine(name, d, mode):
    c = header(name, mode)
    for leaf, ld in LEAVES.items():
        s_ip, _ = p2p(d["sid"], ld["idx"])
        c += f"interface Ethernet{ld['idx']}\n   description P2P_{leaf}\n   no switchport\n   mtu 9214\n   ip address {s_ip}/31\n!\n"
    c += f"interface Loopback0\n   ip address {d['lo0']}/32\n!\nip routing\n!\n" + LOOP_POLICY
    c += f"router bgp {SPINE_ASN}\n   router-id {d['lo0']}\n" + COMMON_BGP
    c += """   neighbor UNDERLAY peer group
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN next-hop-unchanged
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community
   neighbor EVPN maximum-routes 0
"""
    for leaf, ld in LEAVES.items():
        _, l_ip = p2p(d["sid"], ld["idx"])
        c += f"   neighbor {l_ip} peer group UNDERLAY\n   neighbor {l_ip} remote-as {ld['asn']}\n   neighbor {l_ip} description {leaf}\n"
    for leaf, ld in LEAVES.items():
        ip = f"10.0.0.{ld['n']}"
        c += f"   neighbor {ip} peer group EVPN\n   neighbor {ip} remote-as {ld['asn']}\n   neighbor {ip} description {leaf}-evpn\n"
    c += """   redistribute connected route-map RM-CONN-2-BGP
   !
   address-family evpn
      neighbor EVPN activate
   !
   address-family ipv4
      neighbor UNDERLAY activate
!
end
"""
    return c


def border_policy(name, d, mode):
    """prefix-lists / route-maps for the WAN edge"""
    bid = d["bid"]
    c = "ip prefix-list PL-FROM-ISP seq 10 permit 0.0.0.0/0\n"
    for i, p in enumerate(INTERNET[1:], start=2):
        c += f"ip prefix-list PL-FROM-ISP seq {i * 10} permit {p}\n"
    for vrf, v in VRFS.items():
        c += f"ip prefix-list PL-{vrf}-SUBNETS seq 10 permit {v['agg']} le 24\n"
    if mode == "te":
        c += f"ip prefix-list PL-RTBH seq 10 permit {RTBH_PLACEHOLDER}\n"
    c += "!\n"
    if mode == "solution":
        c += "route-map RM-ISP-IN permit 10\n   match ip address prefix-list PL-FROM-ISP\n!\n"
        for vrf in VRFS:
            c += f"route-map RM-{vrf}-OUT permit 10\n   match ip address prefix-list PL-{vrf}-SUBNETS\n!\n"
        return c
    # te
    for vrf in VRFS:
        for isp, idata in ISPS.items():
            pri = PRIMARY[vrf] == isp
            lp, comm = (200, COMM_PRI) if pri else (50, COMM_BKP)
            tag = isp[-1]
            c += f"""route-map RM-{vrf}-ISP{tag}-IN permit 10
   description {'primary' if pri else 'backup'} egress for {vrf}
   match ip address prefix-list PL-FROM-ISP
   set local-preference {lp}
   set community {comm}
!
route-map RM-{vrf}-ISP{tag}-OUT permit 5
   description RTBH trigger
   match ip address prefix-list PL-RTBH
   set community {idata['asn']}:666
!
route-map RM-{vrf}-ISP{tag}-OUT permit 10
   match ip address prefix-list PL-{vrf}-SUBNETS
   set metric {MED[vrf][bid]}
"""
            if not pri:
                c += f"   set community {idata['asn']}:80\n"
            c += "!\n"
    return c


def leaf(name, d, mode):
    n, asn = d["n"], d["asn"]
    lo0, vtep = f"10.0.0.{n}", f"10.0.1.{n}"
    vlans = sorted({v for v, _ in d["access"].values()})
    is_border = "bid" in d
    vrfs = list(VRFS) if is_border else sorted({VLANS[v]["vrf"] for v in vlans}, reverse=True)
    c = header(name, mode)
    for v in vlans:
        c += f"vlan {v}\n   name {VLANS[v]['name']}\n!\n"
    for vrf in vrfs:
        c += f"vrf instance {vrf}\n!\n"
    for sname, sd in SPINES.items():
        _, l_ip = p2p(sd["sid"], d["idx"])
        c += f"interface Ethernet{sd['sid']}\n   description P2P_{sname}\n   no switchport\n   mtu 9214\n   ip address {l_ip}/31\n!\n"
    for port, (v, host) in sorted(d["access"].items()):
        c += f"interface Ethernet{port}\n   description HOST_{host}\n   switchport access vlan {v}\n   spanning-tree portfast\n   spanning-tree bpduguard enable\n!\n"
    if is_border:
        for isp, idata in ISPS.items():
            c += f"interface Ethernet{idata['bport']}\n   description WAN_{isp}\n   no switchport\n!\n"
            for vrf, v in VRFS.items():
                b_ip, _ = wan(isp, d["bid"], vrf)
                c += f"interface Ethernet{idata['bport']}.{v['dot1q']}\n   description WAN_{isp}_vrf_{vrf}\n   encapsulation dot1q vlan {v['dot1q']}\n   vrf {vrf}\n   ip address {b_ip}/30\n"
                if mode == "te":
                    c += f"   {BFD}\n"
                c += "!\n"
    c += f"interface Loopback0\n   description ROUTER_ID_EVPN\n   ip address {lo0}/32\n!\ninterface Loopback1\n   description VTEP\n   ip address {vtep}/32\n!\n"
    for v in vlans:
        c += f"interface Vlan{v}\n   description {VLANS[v]['name']}\n   vrf {VLANS[v]['vrf']}\n   ip address virtual {VLANS[v]['gw']}\n!\n"
    c += "interface Vxlan1\n   vxlan source-interface Loopback1\n   vxlan udp-port 4789\n"
    for v in vlans:
        c += f"   vxlan vlan {v} vni {VLANS[v]['vni']}\n"
    for vrf in vrfs:
        c += f"   vxlan vrf {vrf} vni {VRFS[vrf]['l3vni']}\n"
    c += f"!\nip virtual-router mac-address {VMAC}\n!\nip routing\n"
    for vrf in vrfs:
        c += f"ip routing vrf {vrf}\n"
    c += "!\n" + LOOP_POLICY
    if is_border and mode != "base":
        c += border_policy(name, d, mode)
    if not is_border and mode == "te":
        c += f"""ip community-list CL-PRIMARY permit {COMM_PRI}
ip community-list CL-BACKUP permit {COMM_BKP}
!
route-map RM-EVPN-IN permit 10
   description border says primary exit
   match community CL-PRIMARY
   set local-preference 200
!
route-map RM-EVPN-IN permit 20
   description border says backup exit
   match community CL-BACKUP
   set local-preference 50
!
route-map RM-EVPN-IN permit 100
   description everything else unchanged
!
"""
    c += f"router bgp {asn}\n   router-id {lo0}\n" + COMMON_BGP
    c += f"""   neighbor UNDERLAY peer group
   neighbor UNDERLAY remote-as {SPINE_ASN}
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN remote-as {SPINE_ASN}
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community
   neighbor EVPN maximum-routes 0
"""
    for sname, sd in SPINES.items():
        s_ip, _ = p2p(sd["sid"], d["idx"])
        c += f"   neighbor {s_ip} peer group UNDERLAY\n   neighbor {s_ip} description {sname}\n"
    for sname, sd in SPINES.items():
        c += f"   neighbor {sd['lo0']} peer group EVPN\n   neighbor {sd['lo0']} description {sname}-evpn\n"
    c += "   redistribute connected route-map RM-CONN-2-BGP\n   !\n"
    for v in vlans:
        vni = VLANS[v]["vni"]
        c += f"   vlan {v}\n      rd {lo0}:{vni}\n      route-target both {vni}:{vni}\n      redistribute learned\n   !\n"
    c += "   address-family evpn\n      neighbor EVPN activate\n"
    if not is_border and mode == "te":
        c += "      neighbor EVPN route-map RM-EVPN-IN in\n"
    c += "   !\n   address-family ipv4\n      neighbor UNDERLAY activate\n   !\n"
    for vrf in vrfs:
        l3 = VRFS[vrf]["l3vni"]
        c += f"""   vrf {vrf}
      rd {lo0}:{l3}
      route-target import evpn {l3}:{l3}
      route-target export evpn {l3}:{l3}
      router-id {lo0}
      maximum-paths 4 ecmp 4
"""
        if not is_border:
            c += "      redistribute connected\n"
        elif mode != "base":
            peers = []
            for isp, idata in ISPS.items():
                _, i_ip = wan(isp, d["bid"], vrf)
                peers.append(i_ip)
                tag = isp[-1]
                rin, rout = (("RM-ISP-IN", f"RM-{vrf}-OUT") if mode == "solution"
                             else (f"RM-{vrf}-ISP{tag}-IN", f"RM-{vrf}-ISP{tag}-OUT"))
                c += f"""      neighbor {i_ip} remote-as {idata['asn']}
      neighbor {i_ip} description {isp}
      neighbor {i_ip} route-map {rin} in
      neighbor {i_ip} route-map {rout} out
      neighbor {i_ip} maximum-routes 1000
"""
                if mode == "te":
                    c += f"      neighbor {i_ip} send-community\n      neighbor {i_ip} bfd\n"
            c += "      !\n      address-family ipv4\n"
            for p in peers:
                c += f"         neighbor {p} activate\n"
        c += "   !\n"
    return c + "!\nend\n"


def isp(name, d):
    asn = d["asn"]
    c = header(name, "provider-managed")
    c += "interface Ethernet1\n   description CUST_bleaf1\n   no switchport\n!\n"
    c += "interface Ethernet2\n   description CUST_bleaf2\n   no switchport\n!\n"
    cust = []
    for bid in (1, 2):
        for vrf, v in VRFS.items():
            b_ip, i_ip = wan(name, bid, vrf)
            cust.append((b_ip, f"bleaf{bid}-{vrf}"))
            c += f"""interface Ethernet{bid}.{v['dot1q']}
   description CUST_bleaf{bid}_{vrf}
   encapsulation dot1q vlan {v['dot1q']}
   ip address {i_ip}/30
   {BFD}
!
"""
    my_ip, inet_ip = d["inet"]
    c += f"""interface Ethernet3
   description UPSTREAM_inet
   no switchport
   ip address {my_ip}
!
interface Loopback0
   ip address {d['lo0']}/32
!
interface Loopback1
   description other-customer test address
   ip address {d['cust_ip']}/32
!
ip routing
!
ip route {d['cust_net']} Null0
ip route {d['bh']}/32 Null0
!
"""
    for i, p in enumerate(INTERNET, start=1):
        c += f"ip prefix-list PL-TO-CUST seq {i * 10} permit {p}\n"
    c += f"""ip prefix-list PL-CUST seq 10 permit 10.10.0.0/16 le 24
ip prefix-list PL-CUST seq 20 permit 10.30.0.0/16 le 24
ip prefix-list PL-CUST-HOST seq 10 permit 10.10.0.0/16 ge 32
ip prefix-list PL-CUST-HOST seq 20 permit 10.30.0.0/16 ge 32
!
ip community-list CL-BLACKHOLE permit {asn}:666
ip community-list CL-LP80 permit {asn}:80
ip community-list CL-PREPEND3 permit {asn}:903
!
route-map RM-CUST-IN permit 10
   description RTBH: /32 + {asn}:666 -> discard, never exported
   match community CL-BLACKHOLE
   match ip address prefix-list PL-CUST-HOST
   set ip next-hop {d['bh']}
   set community no-export additive
!
route-map RM-CUST-IN permit 20
   description customer-signalled backup
   match community CL-LP80
   match ip address prefix-list PL-CUST
   set local-preference 80
!
route-map RM-CUST-IN permit 30
   match ip address prefix-list PL-CUST
   set local-preference 200
!
route-map RM-CUST-OUT permit 10
   match ip address prefix-list PL-TO-CUST
!
route-map RM-INET-IN permit 10
   set local-preference 100
!
route-map RM-INET-OUT permit 10
   match community CL-PREPEND3
   set as-path prepend {asn} {asn} {asn}
!
route-map RM-INET-OUT permit 20
!
router bgp {asn}
   router-id {d['lo0']}
   maximum-paths 4 ecmp 4
   neighbor CUSTOMER peer group
   neighbor CUSTOMER remote-as {BORDER_ASN}
   neighbor CUSTOMER route-map RM-CUST-IN in
   neighbor CUSTOMER route-map RM-CUST-OUT out
   neighbor CUSTOMER default-originate
   neighbor CUSTOMER bfd
   neighbor CUSTOMER maximum-routes 100
"""
    for b_ip, desc in cust:
        c += f"   neighbor {b_ip} peer group CUSTOMER\n   neighbor {b_ip} description {desc}\n"
    c += f"""   neighbor {inet_ip} remote-as {INET_ASN}
   neighbor {inet_ip} description inet
   neighbor {inet_ip} route-map RM-INET-IN in
   neighbor {inet_ip} route-map RM-INET-OUT out
   network {d['cust_net']}
!
end
"""
    return c


def main():
    root = Path(__file__).resolve().parent.parent
    for mode in ("base", "solution", "te"):
        out = root / "configs" / mode
        out.mkdir(parents=True, exist_ok=True)
        for s, d in SPINES.items():
            (out / f"{s}.cfg").write_text(spine(s, d, mode))
        for l, d in LEAVES.items():
            (out / f"{l}.cfg").write_text(leaf(l, d, mode))
        for i, d in ISPS.items():
            (out / f"{i}.cfg").write_text(isp(i, d))
    print("rendered configs/{base,solution,te}")


if __name__ == "__main__":
    main()
