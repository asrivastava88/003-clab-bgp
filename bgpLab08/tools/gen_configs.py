#!/usr/bin/env python3
"""
bgp-lab08 config renderer (stdlib only).

Two independent EVPN-VXLAN sites joined by a pair of DCI gateways.

The model is the EVPN gateway, not a flat stretch. Each border gateway sets
next-hop-self in the EVPN address family, so:

  - a leaf never tunnels to a VTEP in the other site. It tunnels to its own
    site's gateway, which decapsulates and re-encapsulates toward the far
    gateway. Two VXLAN domains, stitched.
  - the DCI underlay carries only the two gateway loopbacks. Neither site
    needs any route to the other site's leaves.
  - the BUM tree is hierarchical rather than a full mesh across the WAN.

Note the contrast with Lab 04 ticket 2: next-hop-self in the EVPN address
family is a fabric-breaking bug on a spine, because a spine is not a VTEP,
and it is the whole mechanism on a gateway, because a gateway is.

Modes:
  base      both sites complete and working on their own. The DCI link is
            addressed and nothing runs over it.
  solution  the DCI built: underlay session, multihop EVPN session,
            next-hop-self, stitched VNIs and the containment filters.
"""
from pathlib import Path

# ============================ DATA ============================
VMAC = "00:1c:73:00:00:99"
VRF, L3VNI = "RED", 50001

# VLAN 10 is the only L2 domain that crosses the DCI. 20 and 30 are
# site-local and reach each other by L3 only, which is the mix you want.
VLANS = {
    10: {"name": "STRETCH",  "vrf": VRF, "gw": "10.10.10.1/24", "vni": 10010},
    20: {"name": "A_LOCAL",  "vrf": VRF, "gw": "10.20.20.1/24", "vni": 10020},
    30: {"name": "B_LOCAL",  "vrf": VRF, "gw": "10.30.30.1/24", "vni": 10030},
}
STRETCHED = [10]          # the VNIs a gateway instantiates, hence stitches

SITES = {
    "A": {"spine_asn": 65100, "p2p": "10.1.1", "lo0_net": "10.0.0", "lo1_net": "10.0.1"},
    "B": {"spine_asn": 65200, "p2p": "10.2.1", "lo0_net": "10.0.2", "lo1_net": "10.0.3"},
}

SPINES = {"spineA": {"site": "A", "n": 1}, "spineB": {"site": "B", "n": 1}}

# idx = the spine port this device lands on, and its /31 slot
LEAVES = {
    "leafA": {"site": "A", "asn": 65101, "n": 11, "idx": 1, "role": "leaf",
              "vlans": [10, 20], "access": {3: (10, "hA1"), 4: (20, "hA2")}},
    "bgwA":  {"site": "A", "asn": 65104, "n": 14, "idx": 2, "role": "gateway",
              "vlans": STRETCHED, "access": {}, "dci_port": 3,
              "dci": ("172.16.0.1/30", "172.16.0.2", "bgwB")},
    "leafB": {"site": "B", "asn": 65201, "n": 11, "idx": 1, "role": "leaf",
              "vlans": [10, 30], "access": {3: (10, "hB1"), 4: (30, "hB2")}},
    "bgwB":  {"site": "B", "asn": 65204, "n": 14, "idx": 2, "role": "gateway",
              "vlans": STRETCHED, "access": {}, "dci_port": 3,
              "dci": ("172.16.0.2/30", "172.16.0.1", "bgwA")},
}

HOSTS = {
    "hA1": {"ip": "10.10.10.101/24", "gw": "10.10.10.1", "to": "leafA vlan 10 (stretched)"},
    "hA2": {"ip": "10.20.20.101/24", "gw": "10.20.20.1", "to": "leafA vlan 20 (site A only)"},
    "hB1": {"ip": "10.10.10.102/24", "gw": "10.10.10.1", "to": "leafB vlan 10 (stretched)"},
    "hB2": {"ip": "10.30.30.101/24", "gw": "10.30.30.1", "to": "leafB vlan 30 (site B only)"},
}
# ==============================================================


def lo0(site, n):
    return f"{SITES[site]['lo0_net']}.{n}"


def lo1(site, n):
    return f"{SITES[site]['lo1_net']}.{n}"


def p2p(site, idx):
    b = (idx - 1) * 2
    return f"{SITES[site]['p2p']}.{b}", f"{SITES[site]['p2p']}.{b + 1}"


def header(host, mode):
    return f"""! {host} | bgp-lab08 | {mode} | generated by tools/gen_configs.py
hostname {host}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode mstp
!
"""


def site_loop_policy(site):
    """Only this site's own loopbacks ever enter this site's underlay."""
    s = SITES[site]
    return f"""ip prefix-list PL-SITE-LOOPBACKS seq 10 permit {s['lo0_net']}.0/24 eq 32
ip prefix-list PL-SITE-LOOPBACKS seq 20 permit {s['lo1_net']}.0/24 eq 32
!
route-map RM-CONN-2-BGP permit 10
   match ip address prefix-list PL-SITE-LOOPBACKS
!
"""


def spine(name, d, mode):
    site = d["site"]
    asn = SITES[site]["spine_asn"]
    c = header(name, mode)
    members = {k: v for k, v in LEAVES.items() if v["site"] == site}
    for leaf, ld in members.items():
        s_ip, _ = p2p(site, ld["idx"])
        c += (f"interface Ethernet{ld['idx']}\n   description P2P_{leaf}\n"
              f"   no switchport\n   mtu 9214\n   ip address {s_ip}/31\n!\n")
    c += f"interface Loopback0\n   ip address {lo0(site, d['n'])}/32\n!\nip routing\n!\n"
    c += site_loop_policy(site)
    c += f"""router bgp {asn}
   router-id {lo0(site, d['n'])}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN next-hop-unchanged
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community extended
   neighbor EVPN maximum-routes 0
"""
    for leaf, ld in members.items():
        _, l_ip = p2p(site, ld["idx"])
        c += (f"   neighbor {l_ip} peer group UNDERLAY\n"
              f"   neighbor {l_ip} remote-as {ld['asn']}\n"
              f"   neighbor {l_ip} description {leaf}\n")
    for leaf, ld in members.items():
        c += (f"   neighbor {lo0(site, ld['n'])} peer group EVPN\n"
              f"   neighbor {lo0(site, ld['n'])} remote-as {ld['asn']}\n"
              f"   neighbor {lo0(site, ld['n'])} description {leaf}-evpn\n")
    c += """   redistribute connected route-map RM-CONN-2-BGP
   !
   address-family evpn
      neighbor EVPN activate
   !
   address-family ipv4
      neighbor UNDERLAY activate
!
end
"""
    return c


def dci_policy(name, d):
    """The DCI underlay carries exactly two prefixes each way: the local
    gateway's Loopback0 for the EVPN session and Loopback1 for the tunnel.
    The far site never learns a route to any of our leaves."""
    site = d["site"]
    _, _, peer_name = d["dci"]
    pd = LEAVES[peer_name]
    psite = pd["site"]
    return f"""ip prefix-list PL-DCI-OUT seq 10 permit {lo0(site, d['n'])}/32
!
ip prefix-list PL-DCI-IN seq 10 permit {lo0(psite, pd['n'])}/32
!
route-map RM-DCI-OUT permit 10
   description only this gateway's own loopback crosses the DCI
   match ip address prefix-list PL-DCI-OUT
!
route-map RM-DCI-IN permit 10
   description only the far gateway's loopback enters this site
   match ip address prefix-list PL-DCI-IN
!
route-map RM-SITE-OUT permit 10
   description keep DCI-learned prefixes out of our own underlay
   match ip address prefix-list PL-SITE-LOOPBACKS
!
"""


def leaf(name, d, mode):
    site, n, asn = d["site"], d["n"], d["asn"]
    vlans = sorted(d["vlans"])
    is_gw = d["role"] == "gateway"
    spine_name = f"spine{site}"
    spine_n = SPINES[spine_name]["n"]
    c = header(name, mode)
    for v in vlans:
        c += f"vlan {v}\n   name {VLANS[v]['name']}\n!\n"
    c += f"vrf instance {VRF}\n!\n"

    _, l_ip = p2p(site, d["idx"])
    c += (f"interface Ethernet1\n   description P2P_{spine_name}\n"
          f"   no switchport\n   mtu 9214\n   ip address {l_ip}/31\n!\n")

    for port, (v, h) in sorted(d["access"].items()):
        c += (f"interface Ethernet{port}\n   description HOST_{h}\n"
              f"   switchport access vlan {v}\n   spanning-tree portfast\n"
              f"   spanning-tree bpduguard enable\n!\n")

    if is_gw:
        ip, _, peer_name = d["dci"]
        c += (f"interface Ethernet{d['dci_port']}\n   description DCI_{peer_name}\n"
              f"   no switchport\n   mtu 9214\n   ip address {ip}\n!\n")

    if is_gw:
        # One loopback for router-id, EVPN peering AND the VXLAN source.
        # next-hop-self rewrites the next hop to the update-source, so if the
        # peering source were a different interface from the VTEP, the far
        # site would be told to tunnel to an address that is not a tunnel
        # endpoint. Collapsing them removes the question entirely.
        c += (f"interface Loopback0\n   description ROUTER_ID_EVPN_AND_VTEP\n"
              f"   ip address {lo0(site, n)}/32\n!\n")
    else:
        c += (f"interface Loopback0\n   description ROUTER_ID_EVPN\n"
              f"   ip address {lo0(site, n)}/32\n!\n"
              f"interface Loopback1\n   description VTEP\n"
              f"   ip address {lo1(site, n)}/32\n!\n")

    # A gateway stitches VLAN 10 at layer 2 and carries no SVI for it. The
    # anycast gateway for that subnet lives on the leaves in both sites.
    if not is_gw:
        for v in vlans:
            c += (f"interface Vlan{v}\n   description {VLANS[v]['name']}\n   vrf {VRF}\n"
                  f"   ip address virtual {VLANS[v]['gw']}\n!\n")

    src = "Loopback0" if is_gw else "Loopback1"
    c += f"interface Vxlan1\n   vxlan source-interface {src}\n   vxlan udp-port 4789\n"
    for v in vlans:
        c += f"   vxlan vlan {v} vni {VLANS[v]['vni']}\n"
    c += f"   vxlan vrf {VRF} vni {L3VNI}\n!\n"
    if not is_gw:
        c += f"ip virtual-router mac-address {VMAC}\n!\n"
    c += f"ip routing\nip routing vrf {VRF}\n!\n"
    c += site_loop_policy(site)
    if is_gw and mode == "solution":
        c += dci_policy(name, d)

    s_ip, _ = p2p(site, d["idx"])
    # the site-facing half of the gateway rewrite: routes arriving from the
    # DCI must be handed to our own leaves with OUR VTEP as the next hop
    gw_nhs = ("   ! site-facing half of the gateway: our leaves tunnel to us,\n"
              "   ! never to a VTEP in the other site\n"
              "   neighbor EVPN next-hop-self\n") if (is_gw and mode == "solution") else ""
    c += f"""router bgp {asn}
   router-id {lo0(site, n)}
   no bgp default ipv4-unicast
   maximum-paths 4 ecmp 4
   distance bgp 20 200 200
   neighbor UNDERLAY peer group
   neighbor UNDERLAY remote-as {SITES[site]['spine_asn']}
   neighbor UNDERLAY send-community
   neighbor UNDERLAY maximum-routes 12000
   neighbor EVPN peer group
   neighbor EVPN remote-as {SITES[site]['spine_asn']}
   neighbor EVPN update-source Loopback0
   neighbor EVPN ebgp-multihop 3
   neighbor EVPN send-community extended
   neighbor EVPN maximum-routes 0
{gw_nhs}   neighbor {s_ip} peer group UNDERLAY
   neighbor {s_ip} description {spine_name}
"""
    if is_gw and mode == "solution":
        c += f"   neighbor {s_ip} route-map RM-SITE-OUT out\n"
    c += (f"   neighbor {lo0(site, spine_n)} peer group EVPN\n"
          f"   neighbor {lo0(site, spine_n)} description {spine_name}-evpn\n")

    if is_gw and mode == "solution":
        _, peer_ip, peer_name = d["dci"]
        pd = LEAVES[peer_name]
        c += f"""   !
   ! DCI underlay: exchange the two gateway loopbacks and nothing else
   neighbor {peer_ip} remote-as {pd['asn']}
   neighbor {peer_ip} description {peer_name}-dci-underlay
   neighbor {peer_ip} route-map RM-DCI-IN in
   neighbor {peer_ip} route-map RM-DCI-OUT out
   neighbor {peer_ip} maximum-routes 100
   !
   ! DCI overlay: EVPN between the gateways, Loopback0 to Loopback0.
   ! next-hop-self is what makes this a gateway rather than a flat stretch:
   ! the far site tunnels to US, not to our leaves.
   neighbor DCI-EVPN peer group
   neighbor DCI-EVPN remote-as {pd['asn']}
   neighbor DCI-EVPN update-source Loopback0
   neighbor DCI-EVPN ebgp-multihop 3
   neighbor DCI-EVPN next-hop-self
   neighbor DCI-EVPN send-community extended
   neighbor DCI-EVPN maximum-routes 0
   neighbor {lo0(pd['site'], pd['n'])} peer group DCI-EVPN
   neighbor {lo0(pd['site'], pd['n'])} description {peer_name}-dci-evpn
"""
    c += "   redistribute connected route-map RM-CONN-2-BGP\n   !\n"
    for v in vlans:
        vni = VLANS[v]["vni"]
        c += (f"   vlan {v}\n      rd {lo0(site, n)}:{vni}\n"
              f"      route-target both {vni}:{vni}\n      redistribute learned\n   !\n")
    c += "   address-family evpn\n      neighbor EVPN activate\n"
    if is_gw and mode == "solution":
        c += "      neighbor DCI-EVPN activate\n"
    c += "   !\n   address-family ipv4\n      neighbor UNDERLAY activate\n"
    if is_gw and mode == "solution":
        _, peer_ip, _ = d["dci"]
        c += f"      neighbor {peer_ip} activate\n"
    c += "   !\n"
    c += (f"   vrf {VRF}\n      rd {lo0(site, n)}:{L3VNI}\n"
          f"      route-target import evpn {L3VNI}:{L3VNI}\n"
          f"      route-target export evpn {L3VNI}:{L3VNI}\n"
          f"      router-id {lo0(site, n)}\n      maximum-paths 4 ecmp 4\n"
          f"      redistribute connected\n   !\n")
    return c + "!\nend\n"


def host(name, d):
    c = header(name, "endpoint")
    c += (f"! {name} -> {d['to']}\n!\nspanning-tree mode none\n!\n"
          f"interface Ethernet1\n   description UPLINK\n   no switchport\n"
          f"   ip address {d['ip']}\n!\n"
          f"ip routing\n!\nip route 0.0.0.0/0 {d['gw']}\n!\nend\n")
    return c


def main():
    root = Path(__file__).resolve().parent.parent
    for mode in ("base", "solution"):
        out = root / "configs" / mode
        out.mkdir(parents=True, exist_ok=True)
        for s, d in SPINES.items():
            (out / f"{s}.cfg").write_text(spine(s, d, mode))
        for l, d in LEAVES.items():
            (out / f"{l}.cfg").write_text(leaf(l, d, mode))
        for h, d in HOSTS.items():
            (out / f"{h}.cfg").write_text(host(h, d))
    print("rendered configs/{base,solution}")


if __name__ == "__main__":
    main()
