#!/usr/bin/env python3
"""bgp-lab13 config generator.

AS 65010 "NORTHSTAR" runs three sites and buys every kind of interconnect
there is: dark fibre, long-haul waves, IP transit (one of them across a
transpacific cable), two IX ports, two PNIs to a CDN, and a redundant pair of
cloud interconnects.

Everything here is fictional. Peer address space is 100.64.0.0/10, which is
reserved and never globally routed, standing in for real routable space so
nothing in this lab teaches you to filter the wrong thing. Our own space is
RFC 5737 documentation prefixes standing in for /20s.
"""
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "configs", "solution")

US = 65010
# local-pref hierarchy. The whole peering strategy is these five numbers.
LP = {"cloud": 400, "pni": 300, "ix": 200, "transit1": 100, "transit2": 90}
# community tagged inbound so every route carries where it came from
CM = {"cloud": f"{US}:400", "pni": f"{US}:300", "ix_rs": f"{US}:200",
      "ix_bilat": f"{US}:201", "transit1": f"{US}:100", "transit2": f"{US}:101"}

OUR_PREFIXES = ["192.0.2.0/24", "198.51.100.0/24", "203.0.113.0/24"]
MTU_BB, MTU_HANDOFF = 9100, 1500

# who originates what, on our side
ORIGINATE = {"sea1": ["198.51.100.0/24"], "ash1": ["203.0.113.0/24", "192.0.2.0/24"]}

PEER_SPACE = {
    65100: ["100.100.0.0/16"],
    65200: ["100.101.0.0/16"],
    65401: ["100.110.0.0/16"],
    65402: ["100.111.0.0/16"],
    65500: ["100.120.0.0/17", "100.120.128.0/17"],
    65600: ["100.130.0.0/16", "100.131.0.0/16"],
}
# reachable only through transit, nobody peers for it
TRANSIT_ONLY = ["100.200.0.0/16"]
# the rest of the DFZ, as our transits see it
DFZ_AGGREGATES = ["100.64.0.0/12", "100.80.0.0/12"]

HDR = "! {name} | bgp-lab13 | {role} | generated by tools/gen_configs.py\n"
BASE = """hostname {name}
!
service routing protocols model multi-agent
!
no aaa root
username admin privilege 15 role network-admin secret 0 admin
!
spanning-tree mode none
!
"""

def iface(n, desc, ip, mtu, ospf_cost=None, ospf_area=None):
    s = f"interface {n}\n   description {desc}\n   no switchport\n   mtu {mtu}\n   ip address {ip}\n"
    if ospf_cost is not None:
        s += f"   ip ospf cost {ospf_cost}\n"
    if ospf_area is not None:
        s += f"   ip ospf area {ospf_area}\n"
    return s + "!\n"

def loopback(n, ip, desc=""):
    d = f"   description {desc}\n" if desc else ""
    return f"interface Loopback{n}\n{d}   ip address {ip}\n!\n"

def plist(name, entries):
    out = ""
    for i, e in enumerate(entries, start=1):
        out += f"ip prefix-list {name} seq {i*10} {e}\n"
    return out + "!\n"

# --------------------------------------------------------------- our edge
def our_policy():
    """Prefix-lists and route-maps shared by sea1, sea2 and ash1."""
    s = ""
    s += plist("PL-OUR-SPACE", [f"permit {p}" for p in OUR_PREFIXES])
    # Bogons. 100.64.0.0/10 is deliberately NOT here: in this lab it stands in
    # for globally routable space. In production it belongs in this list.
    s += plist("PL-BOGON", [
        "deny 0.0.0.0/0",
        "deny 0.0.0.0/8 le 32",
        "deny 10.0.0.0/8 le 32",
        "deny 127.0.0.0/8 le 32",
        "deny 169.254.0.0/16 le 32",
        "deny 172.16.0.0/12 le 32",
        "deny 192.168.0.0/16 le 32",
        "deny 224.0.0.0/4 le 32",
        "deny 240.0.0.0/4 le 32",
        "permit 0.0.0.0/0 ge 8 le 24",
    ])
    # what each peer class is allowed to announce to us. In production these
    # come from IRR (AS-SET expansion) or RPKI, rebuilt nightly.
    s += plist("PL-IRR-AS65401", ["permit 100.110.0.0/16 le 24"])
    s += plist("PL-IRR-AS65402", ["permit 100.111.0.0/16 le 24"])
    s += plist("PL-IRR-AS65500", ["permit 100.120.0.0/16 le 24"])
    s += plist("PL-CLOUD-REGIONS", ["permit 100.130.0.0/16 le 24", "permit 100.131.0.0/16 le 24"])

    s += plist("PL-OUR-SPACE-ANY", [f"permit {p} le 32" for p in OUR_PREFIXES])

    def rmin(name, allow, lp, comm):
        return (f"route-map {name} deny 5\n"
                f"   description never accept our own space from anyone\n"
                f"   match ip address prefix-list PL-OUR-SPACE-ANY\n"
                f"!\n"
                f"route-map {name} permit 10\n"
                f"   match ip address prefix-list {allow}\n"
                f"   set local-preference {lp}\n"
                f"   set community {comm} additive\n"
                f"!\n")

    s += rmin("RM-TRANSIT1-IN", "PL-BOGON", LP["transit1"], CM["transit1"])
    s += rmin("RM-TRANSIT2-IN", "PL-BOGON", LP["transit2"], CM["transit2"])
    s += rmin("RM-IXRS-IN", "PL-IRR-AS65401", LP["ix"], CM["ix_rs"])
    s += rmin("RM-IXBILAT-IN", "PL-IRR-AS65402", LP["ix"], CM["ix_bilat"])
    s += rmin("RM-PNI-IN", "PL-IRR-AS65500", LP["pni"], CM["pni"])
    s += rmin("RM-CLOUD-IN", "PL-CLOUD-REGIONS", LP["cloud"], CM["cloud"])

    # outbound: our own space and nothing else, to every external peer
    s += ("route-map RM-OUR-SPACE-OUT permit 10\n"
          "   match ip address prefix-list PL-OUR-SPACE\n"
          "!\n")
    return s

def our_edge(name, rid, ifaces, ospf_nets, ebgp, originate, prepend_to=(), passive=()):
    s = HDR.format(name=name, role="AS 65010 edge") + BASE.format(name=name)
    for i in ifaces:
        s += i
    s += loopback(0, f"{rid}/32", "ROUTER_ID / iBGP SOURCE")
    s += "ip routing\n!\n"
    for p in originate:
        s += f"ip route {p} Null0 254\n"
    s += "!\n"
    s += our_policy()
    if prepend_to:
        s += ("route-map RM-TRANSIT1-OUT permit 10\n"
              "   description de-prefer this site for inbound traffic\n"
              "   match ip address prefix-list PL-OUR-SPACE\n"
              f"   set as-path prepend {US} {US}\n"
              "!\n")
    s += f"router ospf 1\n   router-id {rid}\n"
    for n in ospf_nets:
        s += f"   network {n} area 0.0.0.0\n"
    for p in passive:
        s += f"   passive-interface {p}\n"
    s += "   max-lsa 12000\n!\n"
    s += f"router bgp {US}\n   router-id {rid}\n   no bgp default ipv4-unicast\n"
    s += "   distance bgp 20 200 200\n   maximum-paths 4 ecmp 4\n"
    s += "   bgp log-neighbor-changes\n"
    s += "   neighbor IBGP peer group\n"
    s += f"   neighbor IBGP remote-as {US}\n"
    s += "   neighbor IBGP update-source Loopback0\n"
    s += "   neighbor IBGP next-hop-self\n"
    s += "   neighbor IBGP send-community\n"
    s += "   neighbor IBGP maximum-routes 12000\n"
    for peer_rid in ["10.255.0.1", "10.255.0.2", "10.255.0.3"]:
        if peer_rid != rid:
            s += f"   neighbor {peer_rid} peer group IBGP\n"
    for g in ebgp:
        s += f"   neighbor {g['grp']} peer group\n"
        s += f"   neighbor {g['grp']} remote-as {g['asn']}\n"
        s += f"   neighbor {g['grp']} send-community\n"
        s += f"   neighbor {g['grp']} route-map {g['rin']} in\n"
        s += f"   neighbor {g['grp']} route-map {g['rout']} out\n"
        s += f"   neighbor {g['grp']} maximum-routes {g['maxr']}\n"
        for ip, desc in g["peers"]:
            s += f"   neighbor {ip} peer group {g['grp']}\n"
            s += f"   neighbor {ip} description {desc}\n"
    for p in originate:
        s += f"   network {p}\n"
    s += "   !\n   address-family ipv4\n      neighbor IBGP activate\n"
    for g in ebgp:
        s += f"      neighbor {g['grp']} activate\n"
    return s + "!\nend\n"

# --------------------------------------------------------------- externals
def external(name, role, asn, rid, ifaces, originate, dfz=False, peers=None,
             extra_policy="", extra_bgp="", hosts=()):
    s = HDR.format(name=name, role=role) + BASE.format(name=name)
    for i in ifaces:
        s += i
    s += loopback(0, f"{rid}/32")
    # a real address inside the space this AS originates, so pings have
    # something to answer them
    for n, ip in hosts:
        s += loopback(n, f"{ip}/32", "REACHABLE_HOST")
    s += "ip routing\n!\n"
    for p in originate:
        s += f"ip route {p} Null0 254\n"
    s += "!\n"
    s += extra_policy
    s += f"router bgp {asn}\n   router-id {rid}\n   no bgp default ipv4-unicast\n"
    s += "   bgp log-neighbor-changes\n   maximum-paths 4 ecmp 4\n"
    s += extra_bgp
    for ip, pasn, desc, rout in peers or []:
        s += f"   neighbor {ip} remote-as {pasn}\n"
        s += f"   neighbor {ip} description {desc}\n"
        s += "   neighbor {} send-community\n".format(ip)
        if rout:
            s += f"   neighbor {ip} route-map {rout} out\n"
        s += f"   neighbor {ip} maximum-routes 12000\n"
    for p in originate:
        s += f"   network {p}\n"
    s += "   !\n   address-family ipv4\n"
    for ip, *_ in peers or []:
        s += f"      neighbor {ip} activate\n"
    return s + "!\nend\n"

def dfz_policy(origin_map):
    """Advertise other networks' prefixes with their origin AS prepended, so
    AS-path length against a direct peering is a real comparison."""
    s = ""
    for i, (asn, prefixes) in enumerate(sorted(origin_map.items())):
        s += plist(f"PL-ORIG-{asn}", [f"permit {p} le 24" for p in prefixes])
    s += ""
    seq = 10
    for asn in sorted(origin_map):
        s += (f"route-map RM-DFZ-OUT permit {seq}\n"
              f"   match ip address prefix-list PL-ORIG-{asn}\n"
              f"   set as-path prepend {asn}\n!\n")
        seq += 10
    s += f"route-map RM-DFZ-OUT permit {seq}\n   description our own and transit-only space\n!\n"
    return s

def build():
    cfg = {}

    # ---------------- sea1, Westin
    cfg["sea1"] = our_edge(
        "sea1", "10.255.0.1",
        [iface("Ethernet1", "TRANSIT-1A_to_transit1", "10.100.1.1/30", MTU_HANDOFF),
         iface("Ethernet2", "IX-PORT-A_to_seattle_exchange", "10.200.0.10/24", MTU_HANDOFF),
         iface("Ethernet3", "PNI-CDN-A_to_cdn1", "10.150.1.1/30", MTU_BB),
         iface("Ethernet4", "CLOUD-IC-A_to_cloudgw", "10.160.1.1/30", MTU_HANDOFF),
         iface("Ethernet5", "DF-SEA-001_darkfibre_to_sea2", "10.254.0.0/31", MTU_BB, ospf_cost=10),
         iface("Ethernet6", "WAVE-SEA-ASH-A_protected_to_ash1", "10.254.0.2/31", MTU_BB, ospf_cost=100)],
        ["10.255.0.1/32", "10.254.0.0/31", "10.254.0.2/31"],
        [dict(grp="TRANSIT1", asn=65100, rin="RM-TRANSIT1-IN", rout="RM-OUR-SPACE-OUT",
              maxr=12000, peers=[("10.100.1.2", "transit1_PACRIM_TRANSIT-1A")]),
         dict(grp="IXRS", asn=65300, rin="RM-IXRS-IN", rout="RM-OUR-SPACE-OUT",
              maxr=200, peers=[("10.200.0.1", "seattle_exchange_route_server")]),
         dict(grp="IXBILAT", asn=65402, rin="RM-IXBILAT-IN", rout="RM-OUR-SPACE-OUT",
              maxr=100, peers=[("10.200.0.30", "ixpeer2_EVERGREEN_bilateral")]),
         dict(grp="PNI", asn=65500, rin="RM-PNI-IN", rout="RM-OUR-SPACE-OUT",
              maxr=500, peers=[("10.150.1.2", "cdn1_SOUNDVIEW_PNI-CDN-A")]),
         dict(grp="CLOUD", asn=65600, rin="RM-CLOUD-IN", rout="RM-OUR-SPACE-OUT",
              maxr=100, peers=[("10.160.1.2", "cloudgw_CLOUD-IC-A")])],
        ORIGINATE["sea1"])

    # ---------------- sea2, Tukwila. Prepends toward transit1 so sea1 is the
    # preferred inbound entry, and holds the transpacific transit.
    cfg["sea2"] = our_edge(
        "sea2", "10.255.0.2",
        [iface("Ethernet1", "TRANSIT-1B_to_transit1", "10.100.2.1/30", MTU_HANDOFF),
         iface("Ethernet2", "IX-PORT-B_to_seattle_exchange", "10.200.0.11/24", MTU_HANDOFF),
         iface("Ethernet3", "PNI-CDN-B_to_cdn1", "10.150.2.1/30", MTU_BB),
         iface("Ethernet4", "CLOUD-IC-B_to_cloudgw", "10.160.2.1/30", MTU_HANDOFF),
         iface("Ethernet5", "DF-SEA-001_darkfibre_to_sea1", "10.254.0.1/31", MTU_BB, ospf_cost=10),
         iface("Ethernet6", "WAVE-SEA-ASH-B_unprotected_to_ash1", "10.254.0.4/31", MTU_BB, ospf_cost=120),
         iface("Ethernet7", "TRANSIT-2_subsea_to_transit2", "10.201.2.1/30", MTU_HANDOFF)],
        ["10.255.0.2/32", "10.254.0.0/31", "10.254.0.4/31"],
        [dict(grp="TRANSIT1", asn=65100, rin="RM-TRANSIT1-IN", rout="RM-TRANSIT1-OUT",
              maxr=12000, peers=[("10.100.2.2", "transit1_PACRIM_TRANSIT-1B")]),
         dict(grp="TRANSIT2", asn=65200, rin="RM-TRANSIT2-IN", rout="RM-OUR-SPACE-OUT",
              maxr=12000, peers=[("10.201.2.2", "transit2_TRANSPAC_subsea")]),
         dict(grp="IXRS", asn=65300, rin="RM-IXRS-IN", rout="RM-OUR-SPACE-OUT",
              maxr=200, peers=[("10.200.0.1", "seattle_exchange_route_server")]),
         dict(grp="IXBILAT", asn=65402, rin="RM-IXBILAT-IN", rout="RM-OUR-SPACE-OUT",
              maxr=100, peers=[("10.200.0.30", "ixpeer2_EVERGREEN_bilateral")]),
         dict(grp="PNI", asn=65500, rin="RM-PNI-IN", rout="RM-OUR-SPACE-OUT",
              maxr=500, peers=[("10.150.2.2", "cdn1_SOUNDVIEW_PNI-CDN-B")]),
         dict(grp="CLOUD", asn=65600, rin="RM-CLOUD-IN", rout="RM-OUR-SPACE-OUT",
              maxr=100, peers=[("10.160.2.2", "cloudgw_CLOUD-IC-B")])],
        [], prepend_to=("TRANSIT1",))

    # ---------------- ash1, Ashburn. No external peers, originates two prefixes.
    cfg["ash1"] = our_edge(
        "ash1", "10.255.0.3",
        [iface("Ethernet1", "WAVE-SEA-ASH-A_protected_to_sea1", "10.254.0.3/31", MTU_BB, ospf_cost=100),
         iface("Ethernet2", "WAVE-SEA-ASH-B_unprotected_to_sea2", "10.254.0.5/31", MTU_BB, ospf_cost=120)],
        ["10.255.0.3/32", "10.254.0.2/31", "10.254.0.4/31"],
        [], ORIGINATE["ash1"])

    # ---------------- transit1, AS 65100. Two handoffs, sold as diverse.
    t1_origin = {65401: PEER_SPACE[65401], 65402: PEER_SPACE[65402],
                 65500: PEER_SPACE[65500], 65600: PEER_SPACE[65600],
                 65200: PEER_SPACE[65200]}
    cfg["transit1"] = external(
        "transit1", "AS 65100 PACRIM, IP transit", 65100, "10.255.1.1",
        [iface("Ethernet1", "TRANSIT-1A_to_sea1", "10.100.1.2/30", MTU_HANDOFF),
         iface("Ethernet2", "TRANSIT-1B_to_sea2", "10.100.2.2/30", MTU_HANDOFF)],
        PEER_SPACE[65100] + DFZ_AGGREGATES + TRANSIT_ONLY
        + [p for v in t1_origin.values() for p in v],
        peers=[("10.100.1.1", US, "sea1_NORTHSTAR", "RM-DFZ-OUT"),
               ("10.100.2.1", US, "sea2_NORTHSTAR", "RM-DFZ-OUT")],
        extra_policy=dfz_policy(t1_origin),
        hosts=[(1, "100.100.0.1"), (2, "100.200.0.1")])

    # ---------------- transit2, AS 65200. Delivered in Tokyo over TRANSPAC-1.
    t2_origin = {65401: PEER_SPACE[65401], 65402: PEER_SPACE[65402],
                 65500: PEER_SPACE[65500], 65600: PEER_SPACE[65600],
                 65100: PEER_SPACE[65100]}
    cfg["transit2"] = external(
        "transit2", "AS 65200 TRANSPAC, transpacific IP transit", 65200, "10.255.2.1",
        [iface("Ethernet1", "TRANSIT-2_subsea_to_sea2", "10.201.2.2/30", MTU_HANDOFF)],
        PEER_SPACE[65200] + DFZ_AGGREGATES + TRANSIT_ONLY
        + [p for v in t2_origin.values() for p in v],
        peers=[("10.201.2.1", US, "sea2_NORTHSTAR", "RM-DFZ-OUT")],
        extra_policy=dfz_policy(t2_origin),
        hosts=[(1, "100.101.0.1")])

    # ---------------- ixrs, AS 65300. IX route server.
    # It relays ixpeer1, and it also passes two prefixes it should never pass:
    # a transit-sized aggregate and one of OUR prefixes. A correct inbound
    # filter on our side drops both. This is a real IX incident, not a trick.
    # a more-specific of the CDN's /17, and one of our own prefixes
    rs_leak = ["100.120.0.0/18", "192.0.2.0/24"]
    cfg["ixrs"] = external(
        "ixrs", "AS 65300 Seattle Exchange route server", 65300, "10.255.3.1",
        [iface("Ethernet1", "IX_PEERING_LAN", "10.200.0.1/24", MTU_HANDOFF)],
        rs_leak,
        peers=[("10.200.0.10", US, "sea1_NORTHSTAR", "RM-RS-OUT"),
               ("10.200.0.11", US, "sea2_NORTHSTAR", "RM-RS-OUT"),
               ("10.200.0.20", 65401, "ixpeer1_CASCADE", None)],
        extra_policy=plist("PL-RS-LEAK", [f"permit {p}" for p in rs_leak])
        + ("route-map RM-RS-OUT permit 10\n"
           "   match ip address prefix-list PL-RS-LEAK\n"
           "   set as-path prepend 65401\n!\n"
           "route-map RM-RS-OUT permit 20\n!\n"),
        extra_bgp="   neighbor 10.200.0.10 next-hop-self\n"
                  "   neighbor 10.200.0.11 next-hop-self\n")

    # ---------------- ixpeer1, AS 65401. Route-server only, no bilateral.
    cfg["ixpeer1"] = external(
        "ixpeer1", "AS 65401 CASCADE, IX peer via route server only", 65401, "10.255.4.1",
        [iface("Ethernet1", "IX_PEERING_LAN", "10.200.0.20/24", MTU_HANDOFF)],
        PEER_SPACE[65401],
        peers=[("10.200.0.1", 65300, "seattle_exchange_route_server", None)],
        hosts=[(1, "100.110.0.1")])

    # ---------------- ixpeer2, AS 65402. Bilateral only, not on the RS.
    cfg["ixpeer2"] = external(
        "ixpeer2", "AS 65402 EVERGREEN, IX peer bilateral only", 65402, "10.255.4.2",
        [iface("Ethernet1", "IX_PEERING_LAN", "10.200.0.30/24", MTU_HANDOFF)],
        PEER_SPACE[65402],
        peers=[("10.200.0.10", US, "sea1_NORTHSTAR_bilateral", None),
               ("10.200.0.11", US, "sea2_NORTHSTAR_bilateral", None)],
        hosts=[(1, "100.111.0.1")])

    # ---------------- cdn1, AS 65500. Two PNIs, announces two /17s and no /16.
    cfg["cdn1"] = external(
        "cdn1", "AS 65500 SOUNDVIEW CDN, private network interconnect", 65500, "10.255.5.1",
        [iface("Ethernet1", "PNI-CDN-A_to_sea1", "10.150.1.2/30", MTU_BB),
         iface("Ethernet2", "PNI-CDN-B_to_sea2", "10.150.2.2/30", MTU_BB)],
        PEER_SPACE[65500],
        peers=[("10.150.1.1", US, "sea1_NORTHSTAR", "RM-OWN-ONLY"),
               ("10.150.2.1", US, "sea2_NORTHSTAR", "RM-OWN-ONLY")],
        extra_policy=plist("PL-OWN", [f"permit {p}" for p in PEER_SPACE[65500]])
        + "route-map RM-OWN-ONLY permit 10\n   match ip address prefix-list PL-OWN\n!\n",
        hosts=[(1, "100.120.0.1"), (2, "100.120.200.1")])

    # ---------------- cloudgw, AS 65600. The redundant pair. Tags each circuit
    # with a community, and provides no transit between the two circuits.
    cfg["cloudgw"] = external(
        "cloudgw", "AS 65600 cloud interconnect, private peering", 65600, "10.255.6.1",
        [iface("Ethernet1", "CLOUD-IC-A_to_sea1", "10.160.1.2/30", MTU_HANDOFF),
         iface("Ethernet2", "CLOUD-IC-B_to_sea2", "10.160.2.2/30", MTU_HANDOFF)],
        PEER_SPACE[65600],
        peers=[("10.160.1.1", US, "sea1_NORTHSTAR_primary", "RM-CLOUD-A-OUT"),
               ("10.160.2.1", US, "sea2_NORTHSTAR_secondary", "RM-CLOUD-B-OUT")],
        extra_policy=plist("PL-OWN", [f"permit {p}" for p in PEER_SPACE[65600]])
        + ("route-map RM-CLOUD-A-OUT permit 10\n"
           "   match ip address prefix-list PL-OWN\n"
           "   set community 65600:100 additive\n!\n"
           "route-map RM-CLOUD-B-OUT permit 10\n"
           "   match ip address prefix-list PL-OWN\n"
           "   set community 65600:200 additive\n!\n"),
        hosts=[(1, "100.130.0.1"), (2, "100.131.0.1")])
    return cfg

if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for name, text in build().items():
        with open(os.path.join(OUT, f"{name}.cfg"), "w") as f:
            f.write(text)
        print(f"  {name}.cfg  {len(text.splitlines())} lines")
